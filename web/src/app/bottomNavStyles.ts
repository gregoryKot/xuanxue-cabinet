// Стили нижней панели вкладок — телефонный вид навигации (AppNav.tsx).
// Отделены от боковой колонки (sideNavStyles.ts): это два разных вида одной
// механики, и общего у них не осталось ничего, кроме имени ориентира. Файл
// родился делением, когда комментарии про прокрутку и высоту панели вывели
// общий навигационный файл за 150 строк храповика (CLAUDE.md «Храповики»).
import type { CSSProperties } from 'react';

// Отступ панели сверху и снизу. Было 10 и 18 из макета — на телефоне панель
// вырастала до ~106px (10 + 44 + 18 + зона ~34, отзыв 2026-09-18: «слишком
// много пространства»); 18 снизу дублировало системный отступ, который на
// устройстве складывается с ним же. 4 и 4 дают 4 + 44 + 4 = 52 плюс зона —
// высота родной вкладочной панели iOS. 44 не трогаем — пол цели нажатия
// (CLAUDE.md «Доступность»).
const BOTTOM_NAV_PADDING_PX = 4;

// Потолок вклада безопасной зоны в отступ (отзыв владельца 2026-09-22, вторая
// итерация: «нижняя панель всё ещё не та, очень большая, внизу много пустого
// пространства»). Замер на установленном PWA (393×852, без панелей браузера):
// от волоска до низа экрана — 86px (4 + 44 + 4 + вся зона 34), от последнего
// пикселя подписи до низа — 43px, половина панели снизу — пустота. Заметно
// только теперь: до ADR-0110 панель стояла на белой карточке и зона читалась
// её частью, на общей бумаге та же зона — пустое поле страницы.
// Не обнуляем: полоска «Домой» тогда снова ляжет на подписи (отзыв владельца
// 2026-09-12, «План» и «Каналы» перечёркнуты) — ради этого и завели env().
// Потолок 20: iOS рисует полоску на ~8px от края высотой ~5px, а низ подписи
// при потолке 20 — на 24px от края, запас больше 10px, перечеркнуть нечем. 44
// (цель нажатия) не трогаем — пол из CLAUDE.md «Доступность». Итог —
// 4 + 44 + 4 + 20 = 72px вместо 86, пустота под подписью — ~29px вместо 43.
const SAFE_AREA_CAP_PX = 20;

// Панель не участвует в прокрутке: была `position: sticky; bottom: 0` внутри
// скролла документа, и оттяжка (rubber-band) Safari на iOS тащила её за собой
// («нижнее меню скачет», отзыв 2026-09-18). Теперь скроллится не страница, а
// область содержимого внутри оболочки (AppShell.tsx) — панель её сосед в
// колонке высотой в экран, и двигаться ей нечем. `fixed` с распоркой не
// берём: распорка разойдётся с высотой панели при правке отступов. Свой
// `zIndex` тоже не нужен — содержимое в отдельном скроллере и под панель не
// заезжает.
//
// Число дорожек сетки — параметр, не зашитая константа: пунктов то два
// (ученик), то четыре (ассистент), то пять (учитель и админ, ADR-0055
// «Материалы» пятым). Зашитая `repeat(4, 1fr)` уводила пятый пункт на вторую
// строку сетки и рвала высоту панели; заодно у ученика (два пункта из
// четырёх дорожек) вкладки занимали только левую половину — теперь по
// дорожке на пункт.
export function bottomStyle(itemCount: number): CSSProperties {
  return {
    display: 'grid',
    gridTemplateColumns: `repeat(${itemCount}, 1fr)`,
    gap: 4,
    padding: `${BOTTOM_NAV_PADDING_PX}px 12px`,
    // Та же бумага, что у всей страницы (фон body — index.css, верхняя
    // строка — AppShellBrandRow.tsx, цвет строки состояния — theme-color в
    // index.html), не --card: отзыв владельца 2026-09-22 на снимке «Заданий»
    // с телефона — «белый низ с коричневатыми кнопками вижу багом». Белой
    // панель и была единственной белой поверхностью экрана, и тёплая плашка
    // активного пункта на ней читалась коричневым пятном (ADR-0110). Своей
    // непрозрачной поверхности панели не нужно: она ничего не маскирует —
    // содержимое лежит в отдельном скроллере (contentColumnStyle,
    // appShellStyles.ts) и под панель не заезжает, хватает волоска сверху.
    background: 'var(--paper)',
    borderTop: '1px solid var(--line)',
    // Колонка оболочки отдаёт остаток высоты области содержимого — панель не
    // должна сжиматься ни при каком объёме списка.
    flexShrink: 0,
    // Полоска «Домой» лежала прямо на подписях (отзыв 2026-09-12) — зона
    // СКЛАДЫВАЕТСЯ с отступом, не заменяет его. `min()`, не вычитание: там,
    // где зоны нет (браузер, десктоп), env() и так 0, и потолок не меняет
    // отступ (расчёт потолка — у SAFE_AREA_CAP_PX выше).
    paddingBottom: `calc(${BOTTOM_NAV_PADDING_PX}px + min(env(safe-area-inset-bottom), ${SAFE_AREA_CAP_PX}px))`,
  };
}

// Цель нажатия 44px и видимая плашка — разные числа: раньше `minHeight: 44`
// стояла на плашке, и она распухла крупнее макета (отзыв владельца). Тот же
// приём, что у pillBaseStyle (PersonRoleBadge.tsx): невидимая цель — на
// `<Link>` (bottomLinkStyle), видимая плашка — на `<span>` (bottomPillStyle).
export const bottomLinkStyle: CSSProperties = {
  // `minWidth: 0` — как и во flex, grid-колонка по умолчанию не сжимается
  // уже содержимого: без этого длинная подпись раздвинула бы дорожку и
  // потянула за собой горизонтальный скролл (тот же урок, что раньше был у
  // flex-раскладки, pr-k3-fixes.md п.10). Вместе с подрезкой подписи
  // (bottomLabelStyle) это и держит дорожки равными при любом слове.
  minWidth: 0,
  display: 'flex',
  alignItems: 'center',
  justifyContent: 'center',
  minHeight: 44,
  textDecoration: 'none',
};

// Значок и подпись под ним — столбец внутри плашки (ADR-0103, заменил
// ADR-0097: «просто картинки не понятно внизу», отзыв владельца 2026-09-21).
// Числа подобраны так, чтобы панель осталась прежней высоты:
// 3 + 22 (значок, NavIcon.tsx) + 2 + 11 (строка подписи, кегль 10 × 1.1) + 3
// = 41 — меньше цели нажатия 44, а высоту панели задаёт именно она
// (4 + 44 + 4 = 52 плюс безопасная зона, расчёт выше). То есть подпись
// вернулась в то место, которое и так было занято невидимой целью нажатия.
// Тронул любое из чисел — пересчитай: гейт в AppNav.test.tsx складывает их
// заново и не пускает столбец выше 44.
const PILL_PADDING_PX = 3;
const ICON_LABEL_GAP_PX = 2;

// Кегль подписи — 10, как у родной вкладочной панели iOS. Одиннадцатый держался
// на замере в браузере: «Материалы» занимали 61.9px из дорожки в 64 (ADR-0055,
// «Дополнение 2026-09-20»), и запас в 2.1px стал поводом убрать подпись вовсе
// (ADR-0097). На десятом та же подпись — 55.8px, запас 8.2 (тот же замер в
// Chromium на 360px, живой Golos Text; числа в ADR-0103). И само переполнение
// перестало быть опасным — подпись подрезается.
const LABEL_FONT_SIZE_PX = 10;
const LABEL_LINE_HEIGHT = 1.1;

export const bottomPillStyle = (isActive: boolean): CSSProperties => ({
  display: 'flex',
  flexDirection: 'column',
  alignItems: 'center',
  justifyContent: 'center',
  gap: ICON_LABEL_GAP_PX,
  width: '100%',
  // Плашка — flex-элемент ссылки, и у неё тоже минимальный размер по
  // содержимому: без `minWidth: 0` подрезка подписи внутри не сработала бы.
  minWidth: 0,
  padding: `${PILL_PADDING_PX}px 0`,
  borderRadius: 'var(--radius-control)',
  // Активный пункт держится прежде всего тушью, не заливкой: `--ink` против
  // приглушённого `--ink-soft` красит через `currentColor` и штрих значка
  // (NavIcon.tsx), и подпись — одной парой, второй константы не нужно.
  // `--panel` — тихая подложка (ADR-0110), только поддерживает форму плашки
  // поверх бумаги `--paper` панели (bottomStyle выше), сама по себе разницу
  // не несёт.
  color: isActive ? 'var(--ink)' : 'var(--ink-soft)',
  background: isActive ? 'var(--panel)' : 'transparent',
});

/** Подпись под значком. Подрезка многоточием — не украшение, а страховка от
 * урока ADR-0055: ширину подписи можно померить только в браузере, а jsdom
 * этого не видит. Слово, которое не поместилось (другой шрифт-подстановка,
 * новое имя раздела), теперь подрезается внутри своей дорожки вместо того,
 * чтобы раздвинуть её и утянуть панель в горизонтальный скролл. Доступное имя
 * ссылки при этом остаётся целым: подрезает CSS, а не разметка. */
export const bottomLabelStyle: CSSProperties = {
  maxWidth: '100%',
  fontSize: LABEL_FONT_SIZE_PX,
  lineHeight: LABEL_LINE_HEIGHT,
  whiteSpace: 'nowrap',
  overflow: 'hidden',
  textOverflow: 'ellipsis',
};
