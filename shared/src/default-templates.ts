// Шаблоны постов по умолчанию (docs/PLAN.md §1, §6): слово в слово повторяют
// нынешние посты канала. Утренний анонс из PLAN §1 не подтверждён учителем
// (см. PLAN §10) и в defaults не входит.

import type { BroadcastKind } from './domain';

/**
 * Вид шаблона — это вид рассылки (`BroadcastKind`), кроме `manual`: разовую
 * рассылку учитель пишет каждый раз сам, шаблона по умолчанию для неё нет.
 * Общий список имён с `BROADCAST_KINDS` (shared/src/domain.ts): иначе
 * планировщику пришлось бы держать таблицу соответствия трёх разных имён
 * одной сущности.
 */
export const TEMPLATE_KINDS = [
  'lesson_link',
  'recording',
] as const satisfies readonly BroadcastKind[];

export type TemplateKind = (typeof TEMPLATE_KINDS)[number];

export const DEFAULT_TEMPLATES: Record<TemplateKind, string> = {
  lesson_link:
    '[{группа}\n]Через {минут} минут {название}[: {тема}]. Запись будет выложена для всех, кто не может участвовать.\n{ссылка}[ пароль {пароль}]',
  // «— {ссылка}» — необязательный фрагмент: запись бывает видеофайлом в
  // канале по file_id без ссылки (PLAN.md §4 `lessons.recordings`), и без
  // этого правила пост заканчивался бы висячим тире.
  //
  // Длительности в посте с записью нет (отзыв владельца 2026-09-12: «когда
  // отправляем видео, время не нужно описывать»): подстановка
  // `{длительность}` осталась доступной, учитель может вернуть её сам на
  // экране «Шаблоны». В анонсе со ссылкой время, наоборот, нужно.
  recording: '{название}[: {тема}][, ведёт {ведущий}][ — {ссылка}]',
};

/**
 * Текст напоминания об оплате по умолчанию — из PLAN §15, п. 2.5 (ADR-0051);
 * учитель правит его сам на экране «Шаблоны». Просто напоминалка об
 * ежемесячной оплате, без слова «абонемент»: бухгалтер не ведёт оплаты в
 * кабинете (ADR-0157). Скриншот об оплате ученик присылает бухгалтеру напрямую,
 * а не боту, поэтому в тексте `{контакт}`, а не `{ссылка}` на бота (ADR-0159);
 * способ связи («в Telegram», WhatsApp) учитель пишет в самом контакте, из кода
 * он убран; сама подстановка `{ссылка}` остаётся доступной учителю.
 */
export const DEFAULT_PAYMENT_REMINDER_TEMPLATE =
  '{имя}, напоминаем об оплате за {месяц}.\nСкриншот об оплате отправьте {контакт}.';
