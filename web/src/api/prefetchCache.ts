// Кэш промисов данных первого экрана.
//
// Зачем он есть: измерено на проде 2026-09-15 — TTFB любого ответа сервера
// 0.5–1.1 с, а после PR #143 (чанк экрана качается параллельно с
// `GET /api/auth/me`) первый экран всё ещё ждёт цепочку «чанк экрана →
// данные экрана»: хук данных (useAbortableFetch) стартует запрос только
// когда чанк уже пришёл и экран смонтирован. `prefetchFirstScreen.ts` кладёт
// сюда промис сразу после ответа `/auth/me` (роль уже известна) — данные
// летят параллельно с чанком, а хук экрана при монтировании забирает уже
// летящий промис вместо второго запроса.
//
// Правила, которые держит этот файл:
//   - только GET — apiFetch (http.ts) заглядывает сюда лишь для GET, кладёт
//     сюда тоже только prefetchFirstScreen.ts, тоже только GET;
//   - только память — ничего не переживает перезагрузку страницы;
//   - кладётся один раз при старте, сразу после ответа `/auth/me`, не на
//     каждый `refresh()` (FirstScreenPrefetch.tsx — защёлка на один раз);
//   - ключ — адрес запроса ровно как его получает apiFetch (без префикса
//     `/api`). Забирает запись сам apiFetch: ключ совпадает с реальным
//     адресом по построению, а useAbortableFetch о кэше не знает вовсе.
type Clock = () => number;

/** Запись живёт секунды — ровно столько, чтобы дожить до монтирования
 * экрана. Запись, которую первый экран не забрал (ушёл на другой адрес до
 * того, как чанк пришёл), не должна через минуту подменить собой свежий
 * запрос того же пути с другого экрана. */
export const PREFETCH_TTL_MS = 15_000;

interface PrefetchEntry {
  promise: Promise<unknown>;
  expiresAt: number;
}

const cache = new Map<string, PrefetchEntry>();

/**
 * Кладёт промис ответа под путь запроса. К сохранённой записи не подвешен
 * `catch` — он висит на отдельной копии промиса: `take` обязан вернуть
 * исходный, необёрнутый промис, чтобы отказ дошёл до хука и тот показал
 * ошибку. Копия нужна, чтобы запись, которую никто не забрал (экран не
 * открыли, срок истёк), не уронила отказом `unhandledrejection` в консоль.
 */
export function putPrefetched(
  path: string,
  promise: Promise<unknown>,
  now: Clock = Date.now,
): void {
  cache.set(path, { promise, expiresAt: now() + PREFETCH_TTL_MS });
  promise.catch(() => undefined);
}

/**
 * Забирает промис под путём — один раз: запись удаляется при первом же
 * обращении, взяли её или нет. Просроченная запись отдаёт `null`, как и
 * отсутствующая.
 */
export function takePrefetched(
  path: string,
  now: Clock = Date.now,
): Promise<unknown> | null {
  const entry = cache.get(path);
  if (!entry) return null;
  cache.delete(path);
  if (entry.expiresAt < now()) return null;
  return entry.promise;
}
