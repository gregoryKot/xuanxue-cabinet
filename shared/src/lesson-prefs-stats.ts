// Число для школы к выбору «о каких занятиях» и «за сколько» (ADR-0162, п. 5):
// сколько активных учеников этим меню воспользовались. Отдельный файл, а не
// дописанный `lesson-notifications.ts`: тот про выбор самого человека, а это
// сводка для штата по всем сразу, и ответ — три числа, а не чьи-то настройки.

/** Сводка по активным ученикам (люди без единой роли, не заблокированные).
 * Отдаётся только штату школы (`GET /notifications/lesson-prefs-stats`); чьи
 * именно это выборы, из неё не видно. */
export interface LessonPrefsStatsDto {
  /** Все активные ученики — «из скольких». */
  activeStudents: number;
  /** Сколько из них выбрали «только о выбранных» (`lessonScopeMode: selected`). */
  chosenClasses: number;
  /** Сколько из них выбрали своё «за сколько напомнить». */
  ownReminder: number;
}
