// Подсказка ученику, критерии проверки и теги ушли из вопроса экзамена
// (ADR-0128): поля `hint`/`criteria`/`tags` больше не объявлены на схеме
// (exam-item.schema.ts) и не читаются мапперами. Миграция снимает их у
// вопросов, заведённых до этой правки, — иначе значения оставались бы лежать
// в базе мёртвым весом (CLAUDE.md «Отказались от механики — удаляем с
// концами»).
//
// Совместимость с деплоем: старый инстанс, который ещё отвечает, пока
// поднимается новый, читает эти поля как необязательные (`tags` — со
// значением по умолчанию `[]`), поэтому их отсутствие ему не мешает. Если он
// успеет записать поле уже после миграции, это будет лишнее поле без
// читателей, а не сломанный документ. Прошлые редакции внутри `history`
// (зашифрованный JSON) миграция не трогает: мапперы их поля больше не
// читают, а переписывать историю ради этого незачем.
//
// Идемпотентна по построению — фильтр по `$or` на `$exists: true` любого из
// трёх полей, второй запуск не находит ни одного документа.
import type { mongo } from 'mongoose';

type Db = mongo.Db;

const EXAM_ITEMS = 'exam_items';

export const examItemsWithoutHintCriteriaTags = {
  id: '0015-exam-items-without-hint-criteria-tags',
  async up(db: Db): Promise<void> {
    await db.collection(EXAM_ITEMS).updateMany(
      {
        $or: [
          { hint: { $exists: true } },
          { criteria: { $exists: true } },
          { tags: { $exists: true } },
        ],
      },
      { $unset: { hint: '', criteria: '', tags: '' } },
    );
  },
};
