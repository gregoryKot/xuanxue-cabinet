// Число для школы к настройкам напоминаний (ADR-0185): сколько активных учеников
// отметили занятия, о которых хотят напоминания, и сколько выбрали своё «за сколько».
// Отдельный файл, а не дописанный `lesson-notifications.ts`: тот про выбор самого
// человека, а это сводка для штата по всем сразу, и ответ — три числа, а не чьи-то
// настройки.

/** Сводка по активным ученикам (люди без единой роли, не заблокированные).
 * Отдаётся только штату школы (`GET /notifications/lesson-prefs-stats`); чьи
 * именно это выборы, из неё не видно. */
export interface LessonPrefsStatsDto {
  /** Все активные ученики — «из скольких». */
  activeStudents: number;
  /** Сколько из них отметили хотя бы одно занятие расписания или отдельное занятие
   * для напоминаний (`reminderClassIds` или `reminderLessonIds` не пусты). */
  withReminders: number;
  /** Сколько из них выбрали своё «за сколько напомнить», в том числе `0` — «в момент
   * начала занятия». */
  ownReminder: number;
}
