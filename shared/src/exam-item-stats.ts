// Статистика вопроса (`GET /exam-items/:id/stats`,
// `GET /exam-items/stats-summary`, слой 4.8, docs/PLAN.md §11): «У вопроса
// видно: сколько раз его задавали, сколько раз ответили верно, какие
// варианты выбирали». Прямая граница ТЗ: не психометрика — ни сложности по
// модели Раша, ни дискриминации, только то, что учитель может прочитать и с
// чем может что-то сделать. Считается по сданным попыткам (`submitted`/
// `graded`) — попытка в работе (`in_progress`) не в счёт: ученик мог не
// закончить её или ещё передумает менять ответ.
import type { ExamItemKind } from './exam-items';

/** Вариант в статистике — сколько раз его выбирали и верный ли он (по
 * текущей редакции вопроса: учителю нужно решать, что делать с
 * вопросом сегодня, а не разбирать историю правок). Не экспортирован
 * отдельно — потребители снаружи модуля берут форму варианта из
 * `NonNullable<ExamItemStatsDto['options']>[number]`, чтобы не плодить
 * второй именованный экспорт в барреле shared/src/index.ts (CLAUDE.md
 * «Файлы»: единственный баррель проекта и так растёт с каждым слоем). */
interface ExamItemOptionStatsDto {
  id: string;
  text: string;
  correct: boolean;
  chosenCount: number;
  /** Картинка варианта (ADR-0035) — иначе строку статистики у варианта без
   * подписи не с чем сопоставить. */
  imageId?: string;
}

export interface ExamItemStatsDto {
  itemId: string;
  kind: ExamItemKind;
  /** В скольких сданных попытках встретился вопрос. */
  askedCount: number;
  /**
   * Сколько раз ответили полностью верно — есть только у вопроса с
   * вариантами (`single`/`multiple`). У текста и видео ответ проверяет
   * учитель сам: автоматическое «верно» здесь было бы придумкой, не тем,
   * что реально произошло (ТЗ 4.8).
   */
  correctCount?: number;
  /**
   * Доля верных ответов (0..1) — только у вопроса с вариантами.
   * `undefined`, если `askedCount` — 0: делить не на что, а показанный «0%»
   * читался бы как «все ошиблись», хотя вопрос просто ещё не задавали.
   */
  correctRate?: number;
  /** Разбивка по вариантам — только у вопроса с вариантами. */
  options?: ExamItemOptionStatsDto[];
  /**
   * В скольких неархивированных экзаменах вопрос стоит хоть в одном блоке
   * (exam-item-references.ts) — не психометрика, просто связь, которую
   * учитель должен увидеть до удаления/архивации вопроса (аудит 2026-09-15,
   * CLAUDE.md «Продуктовая фича = число в своём разделе»): удалить или
   * заархивировать вопрос, стоящий хоть в одном, нельзя — API откажет
   * с названиями этих форм, число здесь предупреждает заранее.
   */
  usedInExamsCount: number;
}

export interface ExamItemStatsSummaryDto {
  /**
   * Сколько вопросов с вариантами, которые хоть раз задавали, отвечают
   * верно реже, чем в половине случаев, — число для карточки-ссылки
   * «Вопросы» на «Экзаменах» (CLAUDE.md «Продуктовая фича = число в своём
   * разделе»). Выбрано из двух чисел, названных в ТЗ 4.8 явно (второе —
   * «сколько вопросов ни разу не задавали»): это зовёт к действию сразу —
   * переписать формулировку, тогда как «не задавали» может означать
   * просто «экзамен с этим вопросом ещё не проводили» и ничего не говорит
   * про сам вопрос.
   */
  strugglingCount: number;
}
