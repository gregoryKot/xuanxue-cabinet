// Показывать ли человеку предложение связать Telegram — один предикат на все
// места, где кабинет это предлагает: экран «Уведомления» (ADR-0065), экран
// «Отправлено» (ADR-0066) и «Проверка работ» через showsTelegramHint; полная
// карта мест и условий — ADR-0066, раздел «Последствия». Не проверка на месте
// в каждом из них: условие тут уже сменилось один раз — отметкой «у меня нет
// телеграма» (ADR-0067), и копия на каждом месте разъехалась бы на первой же
// правке — человек отключит предложение и продолжит видеть кнопку на части
// экранов (CLAUDE.md «Одна механика — один компонент»). Новое условие
// по-прежнему дописывается сюда, а не рядом с вызовом.
//
// Признак — `botChatActive`, не `telegramLinked` (ADR-0042): у вошедшего
// через виджет Telegram `telegramLinked` истинен сразу, личного чата с ботом
// при этом нет, и уведомления молча не доходят. Сама отметка читается не
// здесь: acceptsTelegramOffer.ts — общее место для неё и ещё одного вопроса
// про Telegram (auth/SecondLoginKey.tsx, признак `telegramLinked`), и два
// чтения одного поля разъехались бы на первой же правке. Соседний
// showsTelegramHint (web/src/grading) отвечает на более узкий вопрос —
// показывать ли подсказку на «Проверке работ», — и поэтому смотрит ещё и на
// виды уведомлений роли.
import type { MeDto } from '@xuanxue/shared';
import { acceptsTelegramOffer } from './acceptsTelegramOffer';

/** `me === null` — сессия ещё грузится (AuthProvider не ответил): предложение
 * молчит, а не появляется вспышкой после загрузки. Тот же приём, что у
 * showsTelegramHint. Проверка нужна и здесь отдельно: acceptsTelegramOffer на
 * null тоже отвечает false, но это знание рантайма — tsc его не видит и без
 * своей проверки не пропустит `me.botChatActive` ниже (strictNullChecks). */
export function showsTelegramOffer(me: MeDto | null): boolean {
  if (!me) return false;
  return acceptsTelegramOffer(me) && !me.botChatActive;
}
