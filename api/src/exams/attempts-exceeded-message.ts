// Текст отказа «превышен лимит попыток» (ТЗ 4.4, п.2) — чистая функция,
// вынесена из exam-attempts.service.ts (CLAUDE.md «Файлы»: сервис дробится
// на файлы, а не раздувается).
import { pluralRu } from '@xuanxue/shared';

// Склонение «попытки» — своя форма, отдельная от QUESTION_FORMS (exam-blocks.ts).
const ATTEMPT_FORMS = {
  one: 'попытку',
  few: 'попытки',
  many: 'попыток',
  other: 'попытки',
} as const;

// Отсылки «попросите учителя открыть ещё одну попытку» здесь больше нет
// (решение владельца 2026-09-21): адресно открыть попытку одному человеку
// нечем, единственный рычаг — поле «Число попыток» у самого экзамена, и оно
// поднимает лимит всем сразу. Обещать ученику несуществующий разговор хуже,
// чем назвать факт.
export function attemptsExceededMessage(attemptsUsed: number): string {
  return (
    `Вы использовали ${attemptsUsed} ${pluralRu(attemptsUsed, ATTEMPT_FORMS)} из ` +
    'разрешённых на этот экзамен.'
  );
}
