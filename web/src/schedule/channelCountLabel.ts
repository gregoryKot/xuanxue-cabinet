// Сколько каналов реально получат рассылку занятия — для пометки «без
// каналов» в строке «Расписания» (SlotRow.tsx, ревью п.1). Число каналов
// строка больше не печатает: «1 канал» у каждого из тридцати занятий читался
// шумом (отзыв владельца 2026-10-02), а нулевой случай — поломка, его видно.

/** Занятие хранит channelIds выключенных и удалённых каналов (учитель мог
 * выключить канал на экране «Каналы», занятие об этом не узнаёт) — строка
 * слота считает только те, что реально получат рассылку, иначе занятие с
 * одним выключенным каналом не попало бы в «без каналов». */
export function countActiveChannels(
  channelIds: string[],
  activeChannelIds: ReadonlySet<string>,
): number {
  return channelIds.filter((id) => activeChannelIds.has(id)).length;
}
