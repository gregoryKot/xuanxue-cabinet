// Механика «ждёт подтверждения» удалена с концами (ADR-0034, инцидент
// 2026-09-15: владелец на мгновение увидел экран ожидания между входом и
// присоединением по ссылке). `status: 'invited'` в коде больше не
// принимается вовсе — эта миграция чистит уже накопленных `invited`-людей,
// переводя их в `active` ДО того, как раннер даст приложению слушать порт
// (api/src/migrations/migration.runner.ts). Миграция одноразовая: окно
// деплоя (старый инстанс ещё пишет 'invited' после того, как раннер
// отметил её применённой) и код после revert-PR миграция не закрывает —
// это делает нормализация на чтении (api/src/users/normalize-user-status.ts,
// ADR-0034, вариант «б»): `.lean()` не валидирует enum, поэтому `findById`
// не падает и не возвращает null на значении вне `USER_STATUSES`, а молча
// отдаёт документ как есть.
//
// Решение владельца (через агента): такие люди уже входили в кабинет хотя
// бы раз — блокировать лишних школа может кнопкой на «Людях» после миграции,
// вручную и по своему усмотрению, вместо того чтобы гадать заранее, кто из
// них лишний. `joinedViaInviteAt` не трогаем — у части `invited`-людей его
// не было и не появится (они пришли не по ссылке, а ждали ручного
// подтверждения или членства в группе, ADR-0026, до ADR-0030), это не повод
// приписывать им путь, которым они не пользовались.
import type { Db } from 'mongodb';

const USERS = 'users';

export const invitedUsersActive = {
  id: '0007-invited-users-active',
  async up(db: Db): Promise<void> {
    // Идемпотентность бесплатная: второй запуск не найдёт ни одного invited.
    await db
      .collection(USERS)
      .updateMany(
        { status: 'invited' },
        { $set: { status: 'active', updatedAt: new Date() } },
      );
  },
};
