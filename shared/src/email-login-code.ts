// Код из письма — второй способ потратить ту же заявку на вход, что и
// ссылка (ADR-0104). Отдельный файл, не auth.ts: тот стоит у потолка
// файлового храповика (CLAUDE.md «Храповики»), тот же приём, что у me.ts
// (ADR-0059). Общий контракт api и web (CLAUDE.md «Слои»): длину и формат
// читают и DTO в api, и поле ввода в web — расхождение ловит tsc.
//
// Зачем код вообще: приложение, поставленное на экран «Домой» айфона,
// держит свои cookie отдельно от Safari, а ссылка из почты открывается
// всегда в браузере — сессия доставалась браузеру, а приложение оставалось
// снаружи (отзыв владельца 2026-09-21). Код человек переносит руками в то
// окно, которое письмо и запросило, и сессия достаётся ему.

/** Шесть цифр — столько человек переносит из письма в поле за раз, и
 * столько же ограничивает `maxLength` поля ввода в web. Перебор держит не
 * длина, а счётчик попыток у самой заявки (SECURITY §2). */
export const EMAIL_LOGIN_CODE_LENGTH = 6;

/** Только цифры: на телефоне под них открывается цифровая клавиатура, и
 * ноль с буквой «О» не перепутать. Собирается из длины выше, чтобы число
 * жило в одном месте. */
export const EMAIL_LOGIN_CODE_RE = new RegExp(`^[0-9]{${EMAIL_LOGIN_CODE_LENGTH}}$`);

/** Тело `POST /auth/email/code`. `email` — тот же адрес, на который ушло
 * письмо: заявка ищется по нему, а не по одному коду, иначе шесть цифр
 * пришлось бы держать уникальными на всю школу. `inviteCode` — код
 * ссылки-приглашения (ADR-0030/0036), как и у входа по ссылке: без него
 * новый человек в кабинет не попадает. */
export interface VerifyEmailCodeInput {
  email: string;
  code: string;
  inviteCode?: string;
}

/** Один текст на «цифры не те», «код устарел», «код уже потратили» и
 * «попытки кончились» (SECURITY §2) — иначе формулировка подсказывала бы
 * постороннему, какая причина верна. */
export const EMAIL_LOGIN_CODE_INVALID_MESSAGE =
  'Код не подошёл. Сверьте цифры с письмом или запросите новое.';
