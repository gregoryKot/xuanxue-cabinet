// Отчёт браузера о сбое (ADR-0071). До него сбои на стороне браузера не
// доходили до сервера вовсе: упал рендер экрана, остался необработанный
// промис, не догрузился чанк после деплоя — ни строки в логах Railway, ни
// сообщения в Telegram. Вопрос владельца 2026-09-18 «а куда приходят ошибки?»
// был ровно про такой случай; серверную половину закрыл ADR-0053.
//
// Общий контракт api/web: DTO в api объявляется как
// `implements ReportClientErrorInput`, расхождение ловит tsc (CLAUDE.md «Слои»).
//
// Чего в контракте нет и не будет: стека, содержимого формы, набранного
// текста, cookie, заголовков, токенов. Эндпоинт открыт всему интернету
// (падение случается и до входа — экран входа, ссылка-приглашение), поэтому
// полей ровно три и у каждого потолок длины (SECURITY §4).

/** Что именно упало. `chunk` — код экрана не догрузился: после деплоя старых
 * хешированных чанков на сервере уже нет, и открытая вкладка спотыкается на
 * первом же переходе. */
export const CLIENT_ERROR_KINDS = ['render', 'unhandled', 'chunk'] as const;
export type ClientErrorKind = (typeof CLIENT_ERROR_KINDS)[number];

export const CLIENT_ERROR_LIMITS = {
  /** Столько знаков сообщения доезжает до лога — остальное режет сервер. */
  message: 300,
  /** Адрес экрана: длиннее `/planning/507f1f77bcf86cd799439011` не бывает. */
  path: 200,
  /** Потолок DTO. Тело сверх него — уже не отчёт о сбое, а поток данных:
   * 400, не «примем и обрежем». Обрезка (clampClientErrorText) спасает отчёт
   * чуть длиннее нормы, этот потолок отсекает злоупотребление. */
  fieldHardMax: 2000,
} as const;

/** Адрес экрана, а не внешняя ссылка: один ведущий слэш и ни одного пробела.
 * Без проверки в поле `path` приехал бы `https://evil.example/…` и попал бы в
 * лог и в сообщение админу как «адрес сбоя». */
export const CLIENT_ERROR_PATH_RE = /^\/\S*$/;

export interface ReportClientErrorInput {
  kind: ClientErrorKind;
  /** Только `error.message` браузера, без стека и без свойств компонента. */
  message: string;
  /** Адрес экрана без query — `window.location.pathname`. */
  path: string;
}

/** Одна строка не длиннее `max`: переносы схлопываются в пробелы (иначе стек
 * или многострочное сообщение разорвёт строку JSON-лога на несколько),
 * хвост отрезается с многоточием. Зовут обе стороны — браузер перед
 * отправкой, сервер перед записью в лог: клиенту верить нельзя, а ронять
 * отчёт устаревшего клиента четырёхсоткой жалко. */
export function clampClientErrorText(text: string, max: number): string {
  const oneLine = text.replace(/\s+/g, ' ').trim();
  return oneLine.length <= max ? oneLine : `${oneLine.slice(0, max - 1)}…`;
}
