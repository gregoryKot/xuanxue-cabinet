// Стили нижней панели вкладок — телефонный вид навигации (AppNav.tsx).
// Отделены от боковой колонки (sideNavStyles.ts): это два разных вида одной
// механики, и общего у них не осталось ничего, кроме имени ориентира. Файл
// родился делением, когда комментарии про прокрутку и высоту панели вывели
// общий навигационный файл за 150 строк храповика (CLAUDE.md «Храповики»).
import type { CSSProperties } from 'react';

// Отступ панели сверху и снизу. Было 10 и 18 из макета — на живом телефоне
// панель вырастала примерно до 106px (10 + цель нажатия 44 + 18 + безопасная
// зона ~34), и владелец назвал это «слишком много пространства» (отзыв
// 2026-09-18). Восемнадцать снизу макет рисовал ВМЕСТО системного отступа над
// полоской «Домой», а на устройстве они складываются. Четыре сверху и снизу
// дают 4 + 44 + 4 = 52 плюс безопасная зона — ровно высота родной вкладочной
// панели iOS (49pt содержимого + 34pt зоны). Сами 44 не трогаем: это пол цели
// нажатия (CLAUDE.md «Доступность»).
const BOTTOM_NAV_PADDING_PX = 4;

// Панель не участвует в прокрутке вовсе. Была `position: sticky; bottom: 0`
// последней в колонке страницы, то есть внутри скролла документа: на iOS
// оттяжку (rubber-band) и инерцию Safari применяет ко всему документу разом и
// тащит такой элемент за нижний край — владелец прислал снимок, где сверху
// пол-экрана пустой бумаги, а панели нет вообще («нижнее меню скачет», отзыв
// 2026-09-18). Теперь скроллится не страница, а область содержимого внутри
// оболочки (AppShell.tsx): панель — сосед этой области снизу в колонке
// высотой ровно в экран, и двигаться ей нечем. `fixed` с распоркой не берём:
// распорка повторяет высоту панели вторым числом и разойдётся с ней при
// первой же правке отступов. Своего `zIndex` панели тоже больше не нужно —
// содержимое лежит в отдельном скроллере и под панель не заезжает.
//
// Число дорожек сетки — параметр, а не зашитая константа: пунктов на экране
// то два (ученик, navItems.ts: STUDENT_NAV_ITEMS), то четыре (ассистент —
// «Ученики» отфильтрованы по роли в AppNav.tsx), то пять (учитель и админ, с
// ADR-0055 «Материалы» пятым пунктом STAFF_NAV_ITEMS). Раньше здесь была
// зашита `repeat(4, 1fr)`: пятый пункт не поместился бы в ряд и уехал на
// вторую строку сетки, ломая высоту панели, посчитанную выше (4 + 44 + 4 = 52
// плюс безопасная зона) под одну строку. Заодно чинится старый побочный
// эффект того же зашитого числа: у ученика (два пункта из четырёх дорожек)
// вкладки занимали только левую половину панели, правая пустовала — теперь
// каждая дорожка достаётся отрисованному пункту, и половину берёт каждая.
export function bottomStyle(itemCount: number): CSSProperties {
  return {
    display: 'grid',
    gridTemplateColumns: `repeat(${itemCount}, 1fr)`,
    gap: 4,
    padding: `${BOTTOM_NAV_PADDING_PX}px 12px`,
    background: 'var(--card)',
    borderTop: '1px solid var(--line)',
    // Колонка оболочки отдаёт остаток высоты области содержимого — панель не
    // должна сжиматься ни при каком объёме списка.
    flexShrink: 0,
    // Полоска «Домой» на iPhone лежала прямо на подписях (отзыв владельца
    // 2026-09-12, скриншот: «План» и «Каналы» перечёркнуты). Безопасная зона
    // СКЛАДЫВАЕТСЯ с отступом панели, а не заменяет его: env() отдаёт 0 там, где
    // зоны нет, и голый `paddingBottom: env(...)` обнулял бы отступ под
    // подписями в обычном браузере.
    paddingBottom: `calc(${BOTTOM_NAV_PADDING_PX}px + env(safe-area-inset-bottom))`,
  };
}

// Тон подложки активного пункта нижней панели — из макета (screens/
// 1c-planning.html, ADR-0043): светлее --panel (#f0ece3). Отдельного токена
// под один частный случай не заводим — достаточно именованной константы
// рядом с использованием (CLAUDE.md «Без магических чисел»).
const MOBILE_ACTIVE_BACKGROUND = '#f4efe6';

// Цель нажатия 44px и видимая плашка макета (~34px, 8×2 + кегль 12) — разные
// числа, и раньше `minHeight: 44` стояла прямо на плашке: она распухла и
// стала заметно крупнее макета (отзыв владельца). Приём — тот же, что у
// pillBaseStyle (people/PersonRoleBadge.tsx) и buttonStyle
// (components/TextLinkButton.tsx): невидимая цель нажатия на `<Link>`
// (bottomLinkStyle), видимая плашка — на внутреннем `<span>` (bottomPillStyle)
// вокруг подписи, без своей минимальной высоты.
export const bottomLinkStyle: CSSProperties = {
  // `minWidth: 0` — как и во flex, grid-колонка по умолчанию не сжимается
  // уже содержимого: длинная неразрывная подпись раздвинула бы колонку и
  // потянула за собой горизонтальный скролл (тот же урок, что раньше был у
  // flex-раскладки, pr-k3-fixes.md п.10).
  minWidth: 0,
  display: 'flex',
  alignItems: 'center',
  justifyContent: 'center',
  minHeight: 44,
  textDecoration: 'none',
};

export const bottomPillStyle = (isActive: boolean): CSSProperties => ({
  width: '100%',
  padding: '8px 0',
  borderRadius: 'var(--radius-control)',
  textAlign: 'center',
  fontSize: 12,
  overflowWrap: 'anywhere',
  color: isActive ? 'var(--ink)' : 'var(--ink-soft)',
  fontWeight: isActive ? 500 : 400,
  background: isActive ? MOBILE_ACTIVE_BACKGROUND : 'transparent',
});
