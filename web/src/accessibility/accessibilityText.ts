const NO_CONTACT = 'Способ связи школа ещё не указала — **напишите учителю школы**.';
const LOAD_FAILED =
  'Не удалось загрузить способ связи. Обновите страницу или **напишите учителю школы**.';
const HOW_TO_DESCRIBE =
  'Расскажите, **что не получилось** и на каком устройстве: так проще найти причину.';

/** `null` — настройки не загрузились: страница остаётся читаемой и отправляет
 * к учителю. Пусто — школа ничего не указала: то же самое, честной строкой,
 * а не выдуманным адресом. Имя и способ связи те же, что на `/privacy`
 * (ADR-0158): второй настройки нет. */
export function buildAccessibilityContactParagraphs(
  contact: SchoolContact | null,
): string[] {
  if (!contact) return [LOAD_FAILED, HOW_TO_DESCRIBE];
  const { dataControllerName: name, dataControllerContact: address } = contact;
  const paragraphs: string[] = [];
  if (name) paragraphs.push(`Сообщения принимает ${emphasizeContactFact(name)}.`);
  paragraphs.push(
    address
      ? `Если что-то мешает или нужна адаптация, напишите: ${emphasizeContactFact(address)}.`
      : NO_CONTACT,
  );
  paragraphs.push(HOW_TO_DESCRIBE);
  return paragraphs;
}
