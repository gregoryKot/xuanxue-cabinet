// Код ссылки-приглашения, который браузер запомнил при открытии живой
// ссылки `/join/<code>` (ADR-0199). Ученица 2026-11-06 открыла приглашение,
// попросила код на почту, ушла читать письмо, а назад вернулась уже на
// обычный `xuanxue.su`: вкладка внутри мессенджера закрылась. Страница входа
// кода приглашения не знала, и код из письма упёрся в «откройте
// ссылку-приглашение». Теперь страница входа берёт код отсюда и шлёт его со
// всеми способами входа, как это делает сама страница приглашения.
//
// localStorage, не sessionStorage, нарочно: потерянная вкладка — ровно тот
// случай, ради которого код запоминается. Это не токен из SECURITY §2
// («токены в localStorage запрещены»): код приглашения один на школу, он и
// так лежит в адресе, который человек открыл (история браузера, мессенджер,
// канал), даёт только регистрацию учеником и отзывается кнопкой «Обновить»
// на «Людях». Успешный вход его стирает (AuthProvider.tsx): дальше он ни к
// чему, а на экране входа после выхода не должен звать «у вас есть
// приглашение».
import { INVITE_CODE_RE } from '@xuanxue/shared';

const INVITE_CODE_KEY = 'xuanxue:inviteCode';

/** Запомнить код живой ссылки. Не по формату или хранилище недоступно
 * (приватный режим) — тихо ничего: вход со страницы приглашения всё равно
 * несёт код сам, теряется только страховка потерянной вкладки. */
export function rememberInviteCode(code: string): void {
  if (!INVITE_CODE_RE.test(code)) return;
  try {
    localStorage.setItem(INVITE_CODE_KEY, code);
  } catch {
    // недоступное хранилище — не роняем экран приглашения
  }
}

/** Код, запомненный раньше; `undefined` — нет, не по формату или хранилище
 * недоступно. `undefined`, не `null`: так его отдают прямо в `inviteCode?`
 * TelegramLoginSection/OtherLoginMethods, где «нет кода» — отсутствие поля. */
export function rememberedInviteCode(): string | undefined {
  try {
    const code = localStorage.getItem(INVITE_CODE_KEY);
    return code !== null && INVITE_CODE_RE.test(code) ? code : undefined;
  } catch {
    return undefined;
  }
}

/** Стереть: вход состоялся или сервер сказал, что ссылка не действует. */
export function forgetInviteCode(): void {
  try {
    localStorage.removeItem(INVITE_CODE_KEY);
  } catch {
    // недоступное хранилище — стирать нечего
  }
}
