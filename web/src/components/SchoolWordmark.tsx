// Знак школы вместе с названием — одна строка, один вид на все точки входа:
// боковая колонка кабинета (app/AppNav.tsx), строка оболочки без колонки —
// телефон и ученик на мониторе (app/AppShellBrandRow.tsx), колонка экранов до
// входа (EntryColumn.tsx). Знак на входе и знак внутри обязаны совпадать до
// пикселя, иначе человек не узнаёт то же место (CLAUDE.md «Одна механика —
// один компонент»).
import type { CSSProperties } from 'react';
import { SchoolMark } from './SchoolMark';

// Название школы ходит со знаком парой и больше нигде не набирается (CLAUDE.md
// «Повторяющийся текст пользователю — тоже константа»).
const SCHOOL_NAME = 'Школа Сюань-Сюэ';

const wordmarkRowStyle: CSSProperties = {
  display: 'flex',
  alignItems: 'center',
  gap: 10,
  minWidth: 0,
};

// Начертание названия — теперь одно на все три точки входа (боковая колонка
// кабинета, строка оболочки без колонки — AppShellBrandRow.tsx, колонка до
// входа — EntryColumn.tsx) и объявлено ровно здесь. До этой правки было три
// разных набора: антиква 18px/400 в боковой колонке, антиква 21px/500 в
// строке оболочки, гротеск 12px прописными на входе — владелец увидел на
// снимке кабинета двойную антикву разом (название рядом с заголовком экрана,
// screenTitleStyle) и «слишком много шрифтов». Название школы — не заголовок,
// а знак места: по ADR-0043 антиква (Cormorant Garamond) остаётся только
// заголовкам экранов, здесь — гротеск (Golos Text), как у остального текста.
//
// Замер в Chromium на живом Golos Text 500: строка «Школа Сюань-Сюэ» — 139px;
// в боковой колонке кабинета (её самое узкое место среди трёх точек входа)
// под текст доступно 158px — с запасом. `nowrap`+`ellipsis` — не часть
// расчёта, а страховка на время загрузки шрифта: пока грузится свой
// (`font-display: swap`), браузер рисует строку подстановочной гарнитурой, и
// та бывает шире расчёта; тогда название подрежется многоточием внутри
// колонки, а не вылезет за неё.
const wordmarkTitleStyle: CSSProperties = {
  fontSize: 15,
  fontWeight: 500,
  letterSpacing: '0.01em',
  lineHeight: 1.2,
  color: 'var(--ink)',
  minWidth: 0,
  whiteSpace: 'nowrap',
  overflow: 'hidden',
  textOverflow: 'ellipsis',
};

/** Знак и название одной строкой — единственный способ их нарисовать
 * (CLAUDE.md «Одна механика — один компонент»): SchoolBrandLink.tsx
 * оборачивает это в ссылку на главную, EntryColumn.tsx рисует как есть, без
 * ссылки (там своя причина — см. комментарий на месте вызова). Раньше каждая
 * точка входа собирала знак и название сама и получала своё начертание —
 * теперь начертание не проп, а часть этого компонента: снаружи его нельзя
 * переопределить. */
export function SchoolWordmark() {
  return (
    <span style={wordmarkRowStyle}>
      <SchoolMark />
      <span style={wordmarkTitleStyle}>{SCHOOL_NAME}</span>
    </span>
  );
}
