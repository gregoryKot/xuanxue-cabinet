// Часовой пояс ушёл из профиля человека (ADR-0060): поле `users.tz` всегда
// равнялось поясу школы, никогда не менялось и ни на что не влияло, а время
// человеку показывается по часам его устройства. Миграция снимает поле у тех,
// кто успел завестись до этого PR, — иначе мёртвое значение лежало бы в базе
// и однажды кто-нибудь начал бы на него опираться (CLAUDE.md «Отказались от
// механики — удаляем с концами»).
//
// Это contract-шаг, и он безопасен в одном PR с удалением кода, потому что
// expand-шага тут никогда и не требовалось: старый инстанс, который во время
// деплоя ещё отвечает, читал `tz` ровно в одном месте — клал его в `MeDto.tz`
// (auth/user.mapper.ts), а в `web` это поле не читал ни один компонент.
// Пропавшее поле делает `MeDto.tz` равным undefined, JSON.stringify такой
// ключ просто не выводит, и ответ `/api/auth/me` теряет поле, которое никто
// не спрашивал. По той же причине безопасен и откат.
//
// Идемпотентна по построению — фильтр на `tz: { $exists: true }`, второй
// запуск не находит ни одного документа с полем.
import type { mongo } from 'mongoose';

// `mongo` — реэкспорт того же драйвера, что использует mongoose внутри
// (mongoose.mongo === require('mongodb')), поэтому тип `Db` совпадает
// с тем, что отдаёт `connection.db` — без второй копии пакета `mongodb`
// в дереве зависимостей.
type Db = mongo.Db;

const USERS = 'users';

export const dropUserTz = {
  id: '0010-drop-user-tz',
  async up(db: Db): Promise<void> {
    await db
      .collection(USERS)
      .updateMany({ tz: { $exists: true } }, { $unset: { tz: '' } });
  },
};
