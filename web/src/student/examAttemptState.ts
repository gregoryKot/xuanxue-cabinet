// Тексты кабинета про положение ученика по одному экзамену (ТЗ п.1) — чистая
// логика без DOM и без сети, юнит-тест на все ветки (CLAUDE.md «Тесты»).
// Строк ровно две, и они про разное время: `describeExamState` — что с
// экзаменом сейчас, `formatAttemptsLeft` — сколько попыток впереди. Карточка
// показывает вторую только там, где попытку можно начать, иначе на ней
// сталкивались будущее и прошлое (отзыв владельца 2026-09-22, ADR-0120).
//
// Какую кнопку показать (или не показывать вовсе) — не здесь: правило одно
// на кабинет и на бота, `getMyExamAction` в shared/src/my-exams.ts
// (ADR-0091). Раньше оно жило тут же под именем `getExamAction` и
// разъезжалось с тем, что решал бот, — с переездом в shared разъехаться
// негде: экраны читают одну функцию.
import {
  pluralRu,
  myExamAttemptsLeft,
  type GradingOutcome,
  type MyExamDto,
} from '@xuanxue/shared';

const ATTEMPT_FORMS = {
  one: 'попытка',
  few: 'попытки',
  many: 'попыток',
  other: 'попытки',
} as const;

/** Итог проверки человеческими словами (ТЗ п.2, слой 4.7) — заголовок на
 * карточке ученика. Не путать с GRADING_OUTCOME_LABELS_RU в
 * grading/gradingFormInput.ts: там подпись для выпадающего списка учителя
 * («Сдал»), здесь — фраза для читателя-ученика о предмете («Экзамен сдан»),
 * третье лицо, без «вы»: согласование по роду и числу тут не нужно
 * (docs/VOICE.md «Форма „вы“»). needs_work прямо называет действие —
 * доработать, — а что именно, ученик увидит в комментарии учителя рядом
 * (карточка его уже показывает).
 */
const OUTCOME_TEXT: Record<GradingOutcome, string> = {
  passed: 'Экзамен сдан',
  failed: 'Экзамен не сдан',
  needs_work: 'Нужно доработать',
};

export function describeOutcome(outcome: GradingOutcome): string {
  return OUTCOME_TEXT[outcome];
}

/** «Осталось 2 попытки» — строка у кнопки старта, и только там.
 * Карточка (StudentExamCard.tsx) рисует её, когда попытку правда можно
 * начать («Начать», «Пройти ещё раз»), поэтому ветки «ноль» здесь нет:
 * `getMyExamAction` обе эти кнопки даёт только при остатке больше нуля
 * (shared/src/my-exams.ts). Раньше строка висела на каждой карточке первой
 * строкой и спорила с состоянием под собой — «Осталось 6 попыток» над
 * «Отправлено, ждём проверки» (отзыв владельца 2026-09-22, ADR-0120). */
export function formatAttemptsLeft(exam: MyExamDto): string {
  const left = myExamAttemptsLeft(exam);
  return `Осталось ${left} ${pluralRu(left, ATTEMPT_FORMS)}`;
}

/** Что с экзаменом происходит сейчас — первая строка карточки под
 * названием (отзыв владельца 2026-09-22: будущее и прошлое на карточке
 * спорили друг с другом, ADR-0120). `null` — сказать пока нечего: попытки не
 * было, а рядом и так стоят «Осталось N попыток» и кнопка «Начать».
 *
 * Про закрытую временем попытку сказано и то, что время вышло, и то, куда
 * она делась: её закрывает тик планировщика и отправляет учителю тем же
 * путём, что и обычную сдачу (api/src/exams/exam-deadline-close.service.ts).
 * Без второй половины строка пугала бы потерей работы.
 *
 * Ветка «graded» — запасной вариант: для проверенной попытки с оценкой
 * карточка рисует не эту строку, а `describeOutcome` с комментарием учителя
 * (ТЗ п.2, слой 4.7). Текст ниже остаётся на случай, если попытка помечена
 * проверенной, а оценки в ответе почему-то ещё нет (защита от рассинхрона
 * данных, не ожидаемый путь). */
export function describeExamState(exam: MyExamDto): string | null {
  const attempt = exam.lastAttempt;
  if (attempt?.status === 'in_progress') return 'Попытка не закончена';
  if (attempt?.status === 'submitted') {
    return attempt.expired
      ? 'Время вышло, попытка ушла на проверку'
      : 'Отправлено, ждём проверки';
  }
  if (attempt?.status === 'graded') return 'Экзамен проверен';
  if (myExamAttemptsLeft(exam) === 0) return 'Попыток по этому экзамену пока нет';
  return null;
}
