// Статус времени занятия (lessonCountdown.ts) — по одному кейсу на ветку,
// плюс переход летнего времени (CLAUDE.md «Тесты», «Время»).
import { describe, expect, it } from 'vitest';
import { lessonCountdownLabel } from './lessonCountdown';

const TZ = 'Asia/Jerusalem';

describe('lessonCountdownLabel — не сегодня', () => {
  it('другой календарный день — null, часы не считаем', () => {
    expect(
      lessonCountdownLabel('2026-09-21T16:00:00.000Z', '2026-09-20T05:00:00.000Z', TZ),
    ).toBeNull();
  });
});

describe('lessonCountdownLabel — сегодня, уже началось', () => {
  it('момент начала в прошлом — «прошло»', () => {
    expect(
      lessonCountdownLabel('2026-09-20T06:30:00.000Z', '2026-09-20T09:00:00.000Z', TZ),
    ).toBe('прошло');
  });

  it('ровно сейчас — тоже «прошло», не «через 0 часов»', () => {
    const now = '2026-09-20T09:00:00.000Z';
    expect(lessonCountdownLabel(now, now, TZ)).toBe('прошло');
  });
});

describe('lessonCountdownLabel — сегодня, впереди', () => {
  it('меньше часа — минуты, с верным склонением', () => {
    expect(
      lessonCountdownLabel('2026-09-20T09:21:00.000Z', '2026-09-20T09:00:00.000Z', TZ),
    ).toBe('через 21 минуту');
  });

  it('меньше минуты — «через 1 минуту», не «через 0 минут»', () => {
    expect(
      lessonCountdownLabel('2026-09-20T09:00:10.000Z', '2026-09-20T09:00:00.000Z', TZ),
    ).toBe('через 1 минуту');
  });

  it('несколько часов — «через 4 часа» (пример из макета 1c-planning.html)', () => {
    expect(
      lessonCountdownLabel('2026-09-20T13:00:00.000Z', '2026-09-20T09:00:00.000Z', TZ),
    ).toBe('через 4 часа');
  });

  it('ровно один час — единственное число', () => {
    expect(
      lessonCountdownLabel('2026-09-20T10:00:00.000Z', '2026-09-20T09:00:00.000Z', TZ),
    ).toBe('через 1 час');
  });

  it('одиннадцать часов — «часов», не «часа» (CLAUDE.md: без остатка от 10)', () => {
    expect(
      lessonCountdownLabel('2026-09-20T20:00:00.000Z', '2026-09-20T09:00:00.000Z', TZ),
    ).toBe('через 11 часов');
  });
});

// Разница считается между двумя абсолютными моментами (Date.parse), не
// календарными сутками — переход летнего времени Asia/Jerusalem (ночь с 24 на
// 25 октября 2026 года длится 25 часов) не должен исказить арифметику часов,
// в отличие от lib/relativeDay.ts, где сутки — календарная единица.
describe('lessonCountdownLabel — переход летнего времени Asia/Jerusalem', () => {
  it('два часа между моментами по разные стороны перевода стрелок — «через 2 часа»', () => {
    // 24 октября 23:00 UTC и 25 октября 01:00 UTC — ровно два часа разницы
    // независимо от того, что местные часы в Иерусалиме в эту ночь переводят.
    expect(
      lessonCountdownLabel('2026-10-25T01:00:00.000Z', '2026-10-24T23:00:00.000Z', TZ),
    ).toBe('через 2 часа');
  });
});
