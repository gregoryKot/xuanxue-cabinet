// Деление списка заданий на три группы — экран «Задания» (TasksScreen.tsx)
// рисует их под своими рубриками, сверху вниз: живое → на проверке →
// законченное. Чистая функция рядом с экраном, а не выражение в JSX (CLAUDE.md
// «Логика вне компонентов»: ветвление проверяется без DOM).
//
// Отзыв владельца 2026-09-22: в списке вперемешку лежали живые и законченные
// экзамены, и за пять секунд было не понять, что сдавать. Прежнее деление
// (splitNewTasks.ts, удалён вместе с тестом) резало по другому шву — «ещё не
// приступал» против «всё остальное», — и сданная работа, законченная форма и
// возвращённая на доработку лежали в одной куче «Остальные».
//
// Отзыв тестировщицы 2026-09-23: попытка, закрытая по времени (`submitted`,
// `expired: true`), лежала в «Сдавать сейчас» — там же, где не начатое, хотя
// работа уже ушла учителю и нажимать нечего кроме «Пройти ещё раз» про
// СЛЕДУЮЩУЮ попытку. Владелец выбрал третью рубрику «На проверке» вместо
// того, чтобы вернуть такую карточку в «Уже позади» (там она выглядела бы
// законченной, а учитель её ещё не смотрел) — граница «сдана и не
// проверена» теперь отдельная от «нажимать нечего», см. ADR-0130.
//
// Граница «Сдавать сейчас» / остальное — кнопка карточки, то есть общее для
// кабинета и бота `getMyExamAction` (shared/src/my-exams.ts, ADR-0091):
// нечего нажимать — делать нечего. Два исключения из «есть кнопка — сдавать
// сейчас»:
// - сданный экзамен: после «Экзамен сдан» кнопка «Пройти ещё раз» остаётся
//   (учитель лимит попыток не съел), но школа ученика не ждёт — такая
//   карточка уезжает к законченным (ADR-0120);
// - сданная, но ещё не проверенная попытка (`status === 'submitted'`, в том
//   числе `expired: true` — время закрыло попытку раньше учителя): кнопки
//   может не быть вовсе или быть у следующей попытки, но карточка не
//   законченная и не ждущая ученика — она уезжает в «На проверке» раньше,
//   чем остальные правила успевают её увидеть (ADR-0130).
//
// Порядок внутри «Сдавать сейчас» (отзыв владельца 2026-09-22, ADR-0121:
// «идущий экзамен ничем не выделен среди прочих») — попытка с тикающими
// часами идёт первой: у неё есть цена промедления, у остальных карточек её
// нет. Сортировка стабильная (Array.prototype.sort гарантирует это с
// ES2019) — остальные карточки друг относительно друга порядок не меняют.
import { getMyExamAction, type MyExamDto } from '@xuanxue/shared';

export interface TasksSplit {
  /** Ждут действия ученика: начать, продолжить, пройти ещё раз, доработать.
   * Идущая попытка — первой (ADR-0121). */
  toDo: MyExamDto[];
  /** Сдано, учитель ещё не посмотрел — нажимать нечего, но и не позади
   * (ADR-0130, отзыв тестировщицы 2026-09-23). */
  review: MyExamDto[];
  /** Делать нечего: экзамен сдан, попытки кончились. */
  done: MyExamDto[];
}

function isUnderReview(exam: MyExamDto): boolean {
  return exam.lastAttempt?.status === 'submitted';
}

function isWaitingForStudent(exam: MyExamDto): boolean {
  if (isUnderReview(exam)) return false;
  if (getMyExamAction(exam) === null) return false;
  const attempt = exam.lastAttempt;
  return attempt?.outcome !== 'passed';
}

function isRunning(exam: MyExamDto): boolean {
  return exam.lastAttempt?.status === 'in_progress';
}

function byRunningFirst(a: MyExamDto, b: MyExamDto): number {
  return Number(isRunning(b)) - Number(isRunning(a));
}

export function splitTasksToDo(exams: MyExamDto[]): TasksSplit {
  const toDo = exams.filter(isWaitingForStudent).sort(byRunningFirst);
  const review = exams.filter(isUnderReview);
  const done = exams.filter((exam) => !isWaitingForStudent(exam) && !isUnderReview(exam));
  return { toDo, review, done };
}
