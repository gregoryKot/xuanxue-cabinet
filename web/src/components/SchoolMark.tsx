// Знак-печать школы — квадрат киноварью (направление «тихо и благородно»,
// docs/adr/0031-visual-direction-quiet-and-noble.md). Один компонент на две
// точки: шапка кабинета (app/AppShell.tsx) и колонка экранов до входа
// (EntryColumn.tsx). Знак на входе и знак внутри обязаны совпадать до
// пикселя, иначе человек не узнаёт то же место (CLAUDE.md «Одна механика —
// один компонент»).
//
// Киноварь знака не спорит с правилом «один акцент на экране»: печать —
// подпись школы, а не действие, взгляд ищет красное среди кнопок, а не в
// шапке.
import type { CSSProperties } from 'react';

// Название школы ходит со знаком парой — и в шапке, и на входе (CLAUDE.md
// «Повторяющийся текст пользователю — тоже константа»).
export const SCHOOL_NAME = 'Школа Сюань-Сюэ';

const markStyle: CSSProperties = {
  width: 26,
  height: 26,
  flexShrink: 0,
  borderRadius: 3,
  background: 'var(--cinnabar)',
  // Светлая обводка бумагой — печать не липнет к тексту рядом.
  border: '2px solid var(--paper)',
};

/** Декоративный: название школы рядом называет место словами, дублировать
 * его скринридеру нечем. */
export function SchoolMark() {
  return <span style={markStyle} aria-hidden="true" />;
}
