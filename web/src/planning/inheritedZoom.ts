// Что на самом деле уйдёт в рассылку, если поле «Ссылка Zoom на это занятие»
// оставить пустым. Подпись «берётся из расписания» верна, но не отвечает на
// вопрос, который учитель задаёт на этом экране: а есть ли она там вообще
// (отзыв владельца 2026-09-12: «ссылок так и нет» — на листе даты занятия,
// где их и не должно быть видно).
import type { ClassDto } from '@xuanxue/shared';

const FALLBACK = 'Оставьте пустым — берётся из расписания';
const OFFLINE = 'Занятие офлайн — ссылка Zoom ему не нужна';
const MISSING =
  'В расписании ссылки нет — рассылка уйдёт без неё. Впишите её здесь на один раз ' +
  'или в «Расписании» — насовсем';

/** Занятие расписания ещё не загрузилось или не найдено — общая подпись без
 * обещаний: врать «ссылка есть» или «ссылки нет» тут нельзя. */
export function inheritedZoomHint(cls: ClassDto | undefined): string {
  if (!cls) return FALLBACK;
  if (cls.zoomLink)
    return `Оставьте пустым — уйдёт ссылка из расписания: ${cls.zoomLink}`;
  if (cls.format === 'offline') return OFFLINE;
  return MISSING;
}
