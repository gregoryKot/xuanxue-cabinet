// Подпись дня у ближайшего занятия (lib/relativeDay.ts). Пояс задаётся явно,
// а не берётся у машины: CI гоняет vitest ещё и под TZ=Australia/Sydney
// (CLAUDE.md «Время»).
import { describe, expect, it } from 'vitest';
import { capitalize, isToday, relativeDayLabel } from './relativeDay';

const TZ = 'Asia/Jerusalem';

describe('relativeDayLabel', () => {
  it('тот же календарный день в поясе читателя — «сегодня»', () => {
    expect(
      relativeDayLabel('2026-09-20T16:00:00.000Z', '2026-09-20T05:00:00.000Z', TZ),
    ).toBe('сегодня');
  });

  it('следующий день — «завтра»', () => {
    expect(
      relativeDayLabel('2026-09-21T16:00:00.000Z', '2026-09-20T05:00:00.000Z', TZ),
    ).toBe('завтра');
  });

  it('дальше — дата словами, а не «через сколько-то дней»', () => {
    expect(
      relativeDayLabel('2026-09-24T16:00:00.000Z', '2026-09-20T05:00:00.000Z', TZ),
    ).toBe('Чт, 24 сентября');
  });

  it('вечер в поясе читателя уже завтра, хотя по UTC ещё сегодня', () => {
    // 2026-09-20 21:30 UTC — это 2026-09-21 00:30 в Иерусалиме (UTC+3).
    expect(
      relativeDayLabel('2026-09-20T21:30:00.000Z', '2026-09-20T05:00:00.000Z', TZ),
    ).toBe('завтра');
  });
});

// Переход на летнее время Asia/Jerusalem: ночь с 24 на 25 октября 2026 года
// длится 25 часов (стрелки переводят назад с 02:00 на 01:00). Сутки ≠ 24
// часа — вычитание миллисекунд назвало бы занятие 25-го «сегодня»
// (CLAUDE.md «Время»: тест на переход обязателен).
describe('relativeDayLabel — переход летнего времени Asia/Jerusalem', () => {
  it('занятие в первый день после перевода стрелок назад — «завтра»', () => {
    expect(
      relativeDayLabel('2026-10-25T07:00:00.000Z', '2026-10-24T09:00:00.000Z', TZ),
    ).toBe('завтра');
  });

  it('вечер того же дня перевода — всё ещё «сегодня»', () => {
    expect(
      relativeDayLabel('2026-10-24T16:00:00.000Z', '2026-10-24T05:00:00.000Z', TZ),
    ).toBe('сегодня');
  });
});

describe('isToday', () => {
  it('тот же календарный день в поясе читателя — true', () => {
    expect(isToday('2026-09-20T16:00:00.000Z', '2026-09-20T05:00:00.000Z', TZ)).toBe(
      true,
    );
  });

  it('другой день — false', () => {
    expect(isToday('2026-09-21T05:00:00.000Z', '2026-09-20T05:00:00.000Z', TZ)).toBe(
      false,
    );
  });

  it('вечер в поясе читателя уже завтра, хотя по UTC ещё сегодня — false', () => {
    // Тот же момент, что и в тесте relativeDayLabel выше: 21:30 UTC — уже
    // 00:30 следующего дня в Иерусалиме.
    expect(isToday('2026-09-20T21:30:00.000Z', '2026-09-20T05:00:00.000Z', TZ)).toBe(
      false,
    );
  });
});

describe('capitalize', () => {
  it('делает первую букву прописной', () => {
    expect(capitalize('сегодня')).toBe('Сегодня');
  });

  it('уже прописная — строка не меняется', () => {
    expect(capitalize('Чт, 24 сентября')).toBe('Чт, 24 сентября');
  });
});
