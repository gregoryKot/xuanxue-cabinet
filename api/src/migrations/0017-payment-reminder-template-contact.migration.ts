// Переводит текст напоминания об оплате у школы, которая его не правила, на
// текст со `{контакт}` (ADR-0159): скриншот перевода ученик присылает
// бухгалтеру напрямую в Telegram, а не боту, и «пришлите скриншот боту» в
// напоминании стало неправдой.
//
// Одной правки дефолта в коде мало: `paymentReminder.template` лежит в базе,
// только если учитель хоть раз сохранял экран «Шаблоны»; тогда там копия
// прежнего дефолта. Меняем ровно тот текст, что совпадает с прежним дефолтом
// слово в слово, — их два: самый первый (с «абонементом», ADR-0051) и тот,
// на который его заменила 0016 (ADR-0157). Правленый учителем шаблон — его
// выбор, трогать нельзя. Нет поля — ничего не делаем: дефолт подставится на
// чтении (toSettingsDto).
//
// Старые и новый тексты лежат здесь константами, а не берутся из
// `shared/src/default-templates.ts`: иначе следующая правка дефолта
// незаметно переопределит смысл сравнения (тот же приём, что в 0005 и 0016).
import type { mongo } from 'mongoose';

// `mongo` — реэкспорт того же драйвера, что использует mongoose внутри
// (mongoose.mongo === require('mongodb')) — без второй копии пакета `mongodb`.
type Db = mongo.Db;

const SETTINGS = 'settings';
const TEMPLATE_PATH = 'paymentReminder.template';

const PREVIOUS_DEFAULTS = [
  '{имя}, абонемент за {месяц} пока не отмечен оплаченным.\nЕсли вы уже перевели — пришлите скриншот сюда, и мы отметим.[ {ссылка}]',
  '{имя}, напоминаем об оплате за {месяц}.\nКогда переведёте — пришлите скриншот боту.[ {ссылка}]',
];
const NEW_TEMPLATE =
  '{имя}, напоминаем об оплате за {месяц}.\nСкриншот перевода пришлите {контакт} в Telegram.';

export const paymentReminderTemplateContact = {
  id: '0017-payment-reminder-template-contact',
  async up(db: Db): Promise<void> {
    // Идемпотентность бесплатная: второй запуск не найдёт прежних текстов.
    await db
      .collection(SETTINGS)
      .updateMany(
        { [TEMPLATE_PATH]: { $in: PREVIOUS_DEFAULTS } },
        { $set: { [TEMPLATE_PATH]: NEW_TEMPLATE, updatedAt: new Date() } },
      );
  },
};
