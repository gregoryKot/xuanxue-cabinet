// Знак-печать школы — растровая печать-черепаха XUANXUE (решение —
// docs/adr/0084-school-mark-is-a-raster-seal.md). Один компонент на все
// точки входа: боковая колонка кабинета на широком экране (app/AppNav.tsx),
// первая строка над содержимым там, где боковой колонки нет — на телефоне и
// у ученика на мониторе (app/AppShell.tsx), и колонка экранов до входа
// (EntryColumn.tsx). Знак на входе и знак внутри обязаны совпадать до
// пикселя, иначе человек не узнаёт то же место (CLAUDE.md «Одна механика —
// один компонент»).
import type { CSSProperties } from 'react';

// Название школы ходит со знаком парой — в навигации и на входе (CLAUDE.md
// «Повторяющийся текст пользователю — тоже константа»).
export const SCHOOL_NAME = 'Школа Сюань-Сюэ';

// Файл генерируется из одного источника скриптом
// scripts/generate-pwa-icons.mjs — так знак в кабинете, на входе и на
// иконке установленного приложения (манифест PWA) остаётся одним и тем же
// файлом, а не тремя копиями, которые могут разъехаться. Картинка лежит в
// web/public и ходит по URL, не импортом: импорт в JS утянул бы её в
// стартовый бандл (CLAUDE.md «Размер», scripts/check-bundle-size.mjs).
const SCHOOL_MARK_SRC = '/icons/school-mark-64.png';
// Размер знака в интерфейсе. Одно число на стиль и на атрибуты width/height:
// атрибуты браузер читает до загрузки картинки и держит место под неё, стиль
// задаёт итоговый размер — разойдись они, знак бы дёрнулся при загрузке.
const MARK_SIZE_PX = 26;

const markStyle: CSSProperties = {
  width: MARK_SIZE_PX,
  height: MARK_SIZE_PX,
  flexShrink: 0,
  // Знак круглый — у самой печати прозрачные углы, отдельной заливки или
  // обводки, как у прежнего квадрата-заглушки, растру не нужно.
  borderRadius: '50%',
  // img по умолчанию строчный элемент и оставляет узкую щель снизу
  // (зарезервировано под спуск строки шрифта) — на круглом знаке 26px эта
  // щель заметна на глаз.
  display: 'block',
};

/** Декоративный: название школы рядом называет место словами, дублировать
 * его скринридеру нечем — alt="" уже выводит картинку из дерева
 * доступности, aria-hidden поверх пустого alt ничего не добавляет. */
export function SchoolMark() {
  return (
    <img
      src={SCHOOL_MARK_SRC}
      alt=""
      width={MARK_SIZE_PX}
      height={MARK_SIZE_PX}
      style={markStyle}
    />
  );
}
