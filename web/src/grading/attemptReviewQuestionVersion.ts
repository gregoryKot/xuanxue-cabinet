// Редакция вопроса в карточке проверки (аудит 2026-10-01, F62) — чистая
// функция, юнит-тест без DOM (CLAUDE.md «Тесты»). Снимок попытки хранит
// вопрос таким, каким его видел сдающий (ADR-0022); если банк с тех пор
// правили, учитель оценивает не сегодняшнюю формулировку, а ту, что в
// снимке, — и должен это видеть. Первая редакция ничего не сообщает
// (вопрос ещё не правили ни разу, когда его задали) — строки нет, иначе
// каждая карточка обрастала бы бессмысленной «Редакция 1». Сегодняшнюю
// редакцию банка карточка не знает: это второй запрос на каждую попытку,
// сознательно не сделан (correctedFix F62).
const FIRST_VERSION = 1;

export function formatQuestionVersion(version: number | undefined): string | null {
  if (version === undefined || version <= FIRST_VERSION) return null;
  return `Редакция вопроса ${version} — та, что видел ученик`;
}
