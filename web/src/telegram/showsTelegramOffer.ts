// Показывать ли человеку предложение связать Telegram — один предикат на все
// места, где кабинет это предлагает: экран «Уведомления» (ADR-0065), экран
// после сдачи работы, «Профиль», первый вход. Не проверка на месте в каждом
// из них: условие тут будет меняться (ближайшее — отметка «у меня нет
// телеграма»), и четыре копии разъедутся на первой же правке — человек
// отключит предложение и продолжит видеть кнопку на двух экранах из четырёх
// (CLAUDE.md «Одна механика — один компонент»). Новое условие дописывается
// сюда, а не рядом с вызовом.
//
// Признак — `botChatActive`, не `telegramLinked` (ADR-0042): у вошедшего
// через виджет Telegram `telegramLinked` истинен сразу, личного чата с ботом
// при этом нет, и уведомления молча не доходят. Соседний showsTelegramHint
// (web/src/grading) отвечает на более узкий вопрос — показывать ли подсказку
// на «Проверке работ», — и поэтому смотрит ещё и на виды уведомлений роли.
import type { MeDto } from '@xuanxue/shared';

/** `me === null` — сессия ещё грузится (AuthProvider не ответил): предложение
 * молчит, а не появляется вспышкой после загрузки. Тот же приём, что у
 * showsTelegramHint. */
export function showsTelegramOffer(me: MeDto | null): boolean {
  if (!me) return false;
  return !me.botChatActive;
}
