// Часы сервера вместо часов телефона (аудит 2026-10-01, H). Дедлайн попытки
// решает сервер (ТЗ 4.4 п.7), а экран считал остаток по `Date.now()`
// устройства: часы, спешащие на пару минут, запирали ученика в цикле «время
// вышло → перечитать → снова время вышло» со скелетоном вместо формы, а
// отстающие — показывали минуты запаса, когда сервер попытку уже закрыл.
// Сдвиг берётся из заголовка `Date` каждого ответа API (Node ставит его на
// каждый ответ, точность — секунда): `serverNow()` — это `Date.now()` плюс
// сдвиг. Пояс зрителя это не трогает (ADR-0060): сдвиг — про абсолютное
// время, не про зону. Единственная точка сети (http.ts) кормит его сама.
let skewMs = 0;

/** Заголовок `Date` ответа и момент его получения по часам клиента. Нет
 * заголовка или он не разбирается (прокси/CDN отдали мусор) — прежний сдвиг
 * остаётся. */
export function noteServerDate(header: string | null, clientNowMs: number): void {
  if (!header) return;
  const serverMs = Date.parse(header);
  if (!Number.isFinite(serverMs)) return;
  skewMs = serverMs - clientNowMs;
}

/** Текущее время по часам сервера (мс эпохи). Пока ни одного ответа не
 * было — часы устройства как есть. */
export function serverNow(): number {
  return Date.now() + skewMs;
}

/** Только для тестов — сдвиг живёт в модуле на всю вкладку. */
export function resetServerClock(): void {
  skewMs = 0;
}
