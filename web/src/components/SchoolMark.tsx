// Знак-печать школы — квадрат терракотой (направление «Тёплая школа»,
// docs/adr/0043-visual-direction-warm-school.md, заменил ADR-0031). Один
// компонент на три точки: боковая колонка кабинета на широком экране
// (app/AppNav.tsx), первая строка над содержимым там, где боковой колонки
// нет — на телефоне и у ученика на мониторе (app/AppShell.tsx), и колонка
// экранов до входа (EntryColumn.tsx). Знак на входе и знак внутри обязаны
// совпадать до пикселя, иначе человек не узнаёт то же место (CLAUDE.md
// «Одна механика — один компонент»).
//
// Терракота знака не спорит с правилом «один акцент на экране»: печать —
// подпись школы, а не действие, взгляд ищет акцент среди кнопок, а не в
// навигации.
import type { CSSProperties } from 'react';

// Название школы ходит со знаком парой — в навигации и на входе (CLAUDE.md
// «Повторяющийся текст пользователю — тоже константа»).
export const SCHOOL_NAME = 'Школа Сюань-Сюэ';

const markStyle: CSSProperties = {
  width: 26,
  height: 26,
  flexShrink: 0,
  // Макет (docs/adr/0043) рисует знаку отдельный радиус 8px, но в кабинете
  // один радиус контролов на всё (--radius-control, тоже 10px) — заводить
  // токен ради двух пикселей на квадрате 26×26 не стали.
  borderRadius: 'var(--radius-control)',
  background: 'var(--terracotta)',
  // Светлая обводка бумагой — печать не липнет к тексту рядом.
  border: '2px solid var(--paper)',
};

/** Декоративный: название школы рядом называет место словами, дублировать
 * его скринридеру нечем. */
export function SchoolMark() {
  return <span style={markStyle} aria-hidden="true" />;
}
