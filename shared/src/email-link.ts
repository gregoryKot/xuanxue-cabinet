// Привязка почты к уже вошедшему человеку (ADR-0059) — второй ключ входа
// рядом с Telegram, как связка Telegram (ADR-0034) для вошедшего по почте.
// Не четвёртый путь входа: адрес привязывает тот, у кого уже есть сессия, и
// до подтверждения ссылкой из письма он входом не работает (SECURITY §2).
// Общий контракт api и web (CLAUDE.md «Слои»).

/** Тело `POST /auth/email/link` (нужна сессия). Только адрес: чей он —
 * решает `@CurrentUser()`, `userId` в теле не поле ввода (SECURITY §2). */
export interface LinkEmailInput {
  email: string;
}

/** Тело `POST /auth/email/confirm` (`@Public()`): токен из письма. Публичный
 * нарочно — письмо человек открывает там, где ему удобно, и сессии на том
 * устройстве может не быть вовсе. Сессию этот токен не выдаёт (ADR-0059) —
 * он только переносит `pendingEmail` в `email`. */
export interface ConfirmEmailInput {
  token: string;
}

/** Формат токена подтверждения — `randomBytes(32).toString('hex')`, 64 hex,
 * как у токена входа (`EMAIL_LOGIN_TOKEN_RE`): один приём, разные хранилища
 * и разный смысл (ADR-0059). Проверяется и в DTO, и на странице
 * `/email/confirm` — чтобы не звать сервер с обрезанной ссылкой. */
export const EMAIL_CONFIRM_TOKEN_RE = /^[0-9a-f]{64}$/;

/** Адрес уже ключ входа другого человека. Молча перезаписать его нельзя —
 * тот же довод, что у занятого Telegram (ADR-0034): один адрес, один
 * аккаунт, а записи объединяет админ на «Людях». */
export const EMAIL_LINK_TAKEN_MESSAGE =
  'Этот адрес уже привязан к другому аккаунту кабинета. Напишите администратору школы — он объединит записи.';

/** У аккаунта уже есть подтверждённый адрес: сменить ключ входа — не
 * «привязать», а отдельное решение, и делает его админ (ADR-0034 отказал в
 * том же самом для Telegram). */
export const EMAIL_LINK_OTHER_EMAIL_MESSAGE =
  'К этому аккаунту кабинета уже привязана другая почта. Напишите администратору школы, если её нужно сменить.';

/** «Прислать ссылку ещё раз» нажали раньше, чем прошёл кулдаун на тот же
 * адрес. Отказ честный, а не молчаливый: письмо действительно не ушло, и
 * текст говорит, почему ждать не страшно — прежняя ссылка ещё жива.
 * Потолок нужен из-за квоты Resend (100 писем в сутки на бесплатном тарифе):
 * без него повторные нажатия выжигают её и ломают вход по почте всей школе. */
export const EMAIL_CONFIRM_RESEND_TOO_SOON_MESSAGE =
  'Письмо уже отправлено, ссылка из него работает час. Не пришло — посмотрите в «Спаме», а через пару минут можно прислать новое.';

/** Токен неизвестен, просрочен или уже использован — один текст на все три
 * причины (SECURITY §2, как у ссылки входа по почте). */
export const EMAIL_CONFIRM_EXPIRED_MESSAGE =
  'Ссылка для подтверждения устарела. Откройте «Профиль» в кабинете и пришлите её ещё раз.';
