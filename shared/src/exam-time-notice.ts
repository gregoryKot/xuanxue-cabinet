// Слова про время экзамена — одни на кабинет и на бота (CLAUDE.md «Одна
// механика — один компонент»). Отзыв владельца 2026-09-22: «время идёт,
// просто снаружи не видно, можно забыть и потом обнаружить, что время
// вышло». Ловушка была настоящая: дедлайн попытки абсолютный
// (`startedAt + timeLimitMin`, exam-attempt-start.ts), сервер закрывает
// просроченную попытку сам, а при `attemptsAllowed: 1` — значении по
// умолчанию — сгоревшая попытка не даёт ученику вообще ничего до тех пор,
// пока учитель не вернёт работу на доработку. Человек «открыл и отложил на
// потом» терял единственную попытку, ни разу об этом не предупреждённый.
//
// Лечится двумя текстами ниже, и оба обязаны звучать одинаково в кабинете и
// в боте: предупреждение ДО старта (вопрос с подтверждением) и подпись
// «Идёт экзамен» там, где ученик видит список заданий, не заходя в саму
// попытку. Разошлись бы они — ученик, сдающий и там и там, читал бы про
// одно и то же разными словами.
import { formatDurationRu } from './format-duration';

/** Подпись состояния «попытка идёт прямо сейчас» — карточка задания в
 * кабинете и строка списка в боте. Рядом с ней каждый экран рисует свой
 * остаток времени: кабинет тикает посекундно (web/src/attempt/
 * attemptDeadline.ts), бот в неподвижном сообщении округляет до минут. */
// Пока не в барабане shared/src/index.ts: барабан не возит имён, которых
// никто не импортирует (check-shared-exports.mjs, CLAUDE.md «Дубли и мёртвый
// код»). Экспорт вернётся вместе с карточкой, которая эту подпись покажет.
export const EXAM_IN_PROGRESS_LABEL = 'Идёт экзамен';

/** Заголовок подтверждения перед стартом попытки с лимитом времени —
 * ровно то, что просил владелец: «индикацию ВЫ НАЧИНАЕТЕ ЭКЗАМЕН я бы
 * сделал поярче». */
export const EXAM_START_CONFIRM_TITLE = 'Вы начинаете экзамен';
export const EXAM_START_CONFIRM_LABEL = 'Начать экзамен';
/** Отказ ведёт не в никуда, а обратно к списку заданий — человек вправе
 * закрыть вопрос и вернуться, когда у него будет этот час (docs/VOICE.md:
 * кнопка — глагол и действие). */
export const EXAM_START_CANCEL_LABEL = 'Не сейчас';

/** Предупреждение перед стартом: сколько времени даётся, что отсчёт пойдёт
 * сразу и не остановится и чем кончится просрочка. Длительность — через
 * общий `formatDurationRu` («45 минут», «1 час»), не своим склонением. */
export function buildExamStartWarning(timeLimitMin: number): string {
  return (
    `На экзамен — ${formatDurationRu(timeLimitMin)}. Отсчёт пойдёт сразу. ` +
    'Закроете страницу или отложите до вечера — время всё равно идёт. ' +
    'Когда оно выйдет, попытка закроется сама и уйдёт учителю с теми ответами, ' +
    'что вы успели дать.'
  );
}

/** Заголовок и кнопка вопроса перед стартом попытки, которая затирает
 * прежнюю (отзыв тестировщицы 2026-09-23, п.4: «сначала учитель должен
 * проверить, а потом давать ещё раз, иначе люди понатыкают десять попыток»;
 * решение владельца — ADR-0131, willRetryDeletePreviousAttempt в
 * my-exams.ts). Отдельные от EXAM_START_CONFIRM_*: та же кнопка «Начать
 * экзамен» здесь читалась бы как обычный старт, а не как замена прежней
 * работы. */
export const EXAM_RETRY_DELETE_CONFIRM_TITLE = 'Начать заново?';
export const EXAM_RETRY_DELETE_CONFIRM_LABEL = 'Начать заново';

/** Сам факт удаления — отдельной строкой-константой, не только внутри
 * предложения ниже: кабинет ищет её в готовом тексте, чтобы выделить
 * полужирным на экране (CLAUDE.md «Акценты» — маркер `**` живёт только в
 * web/, не здесь), бот показывает предложение как есть. */
export const EXAM_RETRY_DELETE_FACT = 'прошлая попытка удалится';

/** Подсказка учителю у поля «Попыток» в редакторе экзамена (аудит 2026-10-01,
 * F60): учитель поднимает лимит, чтобы «вернуть» ученику экзамен, а по
 * ADR-0131 новая попытка удаляет просроченную непроверенную работу — обе он
 * не увидит. Рядом с EXAM_RETRY_DELETE_FACT: факт удаления живёт в одном
 * файле, чтобы текст ученика и текст учителя не разошлись. */
export const ATTEMPTS_ALLOWED_TIP =
  'Новая попытка заменит просроченную непроверенную работу. Сначала оцените её.';

/** Предупреждение перед повторной попыткой после истёкшего срока — у формы
 * без лимита времени тоже: ученика прерывает не отсутствие часов, а само
 * решение владельца затирать несданное вовремя. `timeLimitMin`
 * необязателен: форма с лимитом добавляет вторую причину поверх первой, а
 * не заменяет её. */
export function buildExamRetryDeleteWarning(timeLimitMin?: number): string {
  const reason =
    'Время на прошлую попытку вышло, доработать её уже нельзя. ' +
    `Начать заново можно, но ${EXAM_RETRY_DELETE_FACT}: учитель увидит только новую попытку.`;
  return timeLimitMin ? `${reason} ${buildExamStartWarning(timeLimitMin)}` : reason;
}
