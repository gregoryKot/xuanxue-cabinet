// Что означает способ получения видео учителю (ADR-0023) — факт способа, не
// «куда идти смотреть»: этого мы для `kind: 'telegram'` не знаем — бот
// пересылает запись в момент получения только тем, у кого уже был чат с
// ним (AttemptReviewMediaItem.tsx, шапка файла), а открывший карточку мог
// завести чат позже или быть другим человеком. Раньше текст утверждал, что
// видео «уже там же», и это могло быть неправдой (отзыв владельца
// 2026-09-21) — что делать дальше, теперь говорит сама карточка: кнопка
// «Прислать мне в Telegram» или объяснение рядом с ней
// (AttemptReviewMediaItem.tsx), а не эта строка. `kind: 'link'` в этот текст
// не попадает: ссылка рисуется отдельно, кликабельной строкой
// (AttemptReviewMedia.tsx), а не пересказывается текстом — открыть её самим
// быстрее, чем прочитать абзац о том, что она есть.
import type { ExamMediaDto } from '@xuanxue/shared';

export function describeMediaSource(media: ExamMediaDto): string {
  if (media.kind === 'telegram') {
    return 'Прислано сообщением боту в Telegram.';
  }
  if (media.kind === 'manual') {
    return media.note
      ? `Отмечено вручную: ${media.note}`
      : 'Отмечено вручную, без подписи.';
  }
  return '';
}
