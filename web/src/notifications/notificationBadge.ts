// Пилюля счётчика у колокольчика (ADR-0063) — чистая логика текста и
// aria-label, без DOM: значок оболочки и сам центр уведомлений берут готовую
// строку, а не считают склонение каждый на своём месте.
//
// Пилюля с цифрой скринридеру ничего не говорит — там нет текста, который он
// прочитал бы, — поэтому счётчик дублируется словами в aria-label.
// `aria-live` на значке не ставится: лента перечитывается сама — и сейчас
// после отметки «прочитано», и тем более когда появится фоновый опрос, — а
// живая область зачитывала бы счётчик вслух при каждом таком обновлении, а не
// когда человек сам заглянул на значок.
import { pluralRu } from '@xuanxue/shared';

/** Имя места одно на оба облика значка — телефонный колокольчик
 * (NotificationBell.tsx) и текстовую ссылку колонки (NotificationsNavLink.tsx),
 * где оно ещё и видимая подпись (CLAUDE.md «Повторяющийся текст пользователю —
 * тоже константа»). `aria-label` ссылки начинается с него же, поэтому
 * голосовое управление по видимой подписи работает. */
export const NOTIFICATIONS_LABEL = 'Уведомления';

/** Выше этого числа пилюля не растёт вширь — показывает потолок «9+», а не
 * трёхзначное число. */
const BADGE_MAX = 9;

const NEW_NOTIFICATIONS_FORMS = {
  one: 'новое',
  few: 'новых',
  many: 'новых',
  other: 'новых',
} as const;

/** '3'; больше BADGE_MAX — потолок '9+'. */
export function badgeText(count: number): string {
  return count > BADGE_MAX ? `${BADGE_MAX}+` : String(count);
}

/** 'Уведомления' при нуле — нечего уточнять; иначе — с настоящим числом
 * (не '9+' — вслух потолок пилюли не нужен, скринридер может сказать и 100). */
export function badgeLabel(count: number): string {
  if (count <= 0) return NOTIFICATIONS_LABEL;
  return `${NOTIFICATIONS_LABEL}, ${count} ${pluralRu(count, NEW_NOTIFICATIONS_FORMS)}`;
}
