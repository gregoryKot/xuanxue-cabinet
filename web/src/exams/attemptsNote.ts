// Честная строка учителю под «Вопросы · N»: попытка ученика хранит снимок
// формы на момент старта (ADR-0022) — правка вопросов в неё никогда не
// попадёт, её увидят только те, кто начнёт экзамен заново. Чистый
// форматтер (CLAUDE.md «Продуктовая фича = число в своём разделе»): на
// чистой базе (попыток ещё не было) — не «0 работ», а молчание, честнее
// нечего предупреждать. pluralRu — общий примитив склонения
// (shared/src/plural-ru.ts); формы «работа/работы/работ» — те же, что у
// grading/gradingQueueHint.ts.
import { pluralRu } from '@xuanxue/shared';

const WORK_FORMS = { one: 'работа', few: 'работы', many: 'работ', other: 'работы' };

/** `total` — ExamAttemptCountDto.total, сколько попыток экзамена уже
 * завели ученики. `null` при 0: предупреждать пока не о чем. */
export function attemptsNote(total: number): string | null {
  if (total === 0) return null;
  return (
    `Экзамен уже проходили — ${total} ${pluralRu(total, WORK_FORMS)}. Новые вопросы ` +
    'увидят только те, кто начнёт заново: в начатой и сданной работе набор ' +
    'вопросов не меняется.'
  );
}
