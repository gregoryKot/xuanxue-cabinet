// Профиль текущей сессии — вынесен из auth.ts отдельным файлом (ADR-0059):
// тот стоит на 152 строках, а второй ключ входа добавляет сюда два поля
// (file-size-ratchet, CLAUDE.md «Храповики»). Общий контракт api и web
// (CLAUDE.md «Слои»): маппер `toMeDto` в api/src/auth/user.mapper.ts и
// AuthProvider в web/src/auth/ читают одну и ту же форму, расхождение ловит
// tsc.
import type { UserRole, UserStatus } from './auth';

/**
 * Профиль текущей сессии для интерфейса. Ученик — это `active` без ролей
 * учителя (ADR-0026), отдельной роли для него нет и в кабинете.
 *
 * `telegramId` и `googleId` сюда не входят: показывать человеку непрозрачный
 * числовой id нечего, а интерфейсу хватает признака «ключ есть»
 * (`telegramLinked` — не id, а «бот меня узнает», ADR-0023, §8.17: им экран
 * попытки решает, показывать ли кнопку бота).
 *
 * Свой адрес почты — наоборот, показываем (ADR-0059): и подтверждённый
 * (`email`), и ждущий подтверждения (`pendingEmail`). Это не послабление
 * SECURITY §2: `GET /auth/me` отвечает только про владельца сессии
 * (`AuthGuard` + `@CurrentUser()`), то есть адрес возвращается тому, у кого
 * он и так в почтовом ящике — раскрывать его тут некому. Без него кабинет
 * не смог бы назвать адрес, который ждёт подтверждения, и напоминание
 * «откройте ссылку из письма» осталось бы без самого письма. Чужие адреса
 * по-прежнему закрыты: `UserDto` на экране «Люди» показывает других людей и
 * email не отдаёт.
 *
 * Часового пояса тут нет намеренно (ADR-0060): время человеку показывается
 * по часам его устройства, и хранить пояс в профиле незачем.
 */
export interface MeDto {
  id: string;
  name: string;
  roles: UserRole[];
  status: UserStatus;
  /** Telegram — ключ входа этого аккаунта (`users.telegramId` есть). */
  telegramLinked: boolean;
  /** «Боту есть куда мне писать» — активный личный чат
   * (`PersonalChats.hasActiveChatFor`), а не просто известный `telegramId`
   * (ADR-0042). Разница видна на входе через виджет Telegram: `telegramId`
   * появляется сразу, а канал заводит только нажатое в боте «Запустить», и
   * без него уведомления молча не доходят. */
  botChatActive: boolean;
  /** Подтверждённый адрес почты есть — вторым ключом входа (ADR-0059) или
   * первым, если человек так и вошёл. Именно по нему ищет
   * `LoginIdentityService.resolveEmailUser`: неподтверждённый адрес входом
   * не работает (SECURITY §2). */
  hasEmail: boolean;
  /** Сам подтверждённый адрес владельца сессии (`users.email`) — тот, по
   * которому ищут вход по почте и привязку Google по почте (SECURITY §2).
   * Отдаётся только в `/auth/me` владельцу сессии, `UserDto` чужие адреса не
   * отдаёт. Необязательное, а не `string | null`: отсутствие — нормальное
   * состояние (вошёл через Telegram), та же форма, что у `pendingEmail`;
   * JSON.stringify и так выбрасывает undefined, и тип повторяет то, что
   * реально едет по сети. `hasEmail` остаётся: на нём стоят SecondLoginKey и
   * другие места, а сервер ставит оба поля из одного `users.email` в одном
   * маппере (user.mapper.spec.ts проверяет согласованность). Баг владельца
   * 2026-09-29: «Профиль» не называл привязанный адрес. */
  email?: string;
  /** Google — ключ входа этого аккаунта (`users.googleId` есть, ADR-0145):
   * «Профиль» показывает «привязан» вместо кнопки «Привязать Google». */
  googleLinked: boolean;
  /** Адрес назван, но ссылку из письма ещё не открыли (`users.pendingEmail`,
   * ADR-0059). Входом не работает; кабинет показывает его на «Профиле» и
   * предлагает прислать ссылку ещё раз. Пусто — ждать нечего. */
  pendingEmail?: string;
  /** Человек сказал, что Telegram у него нет (`users.noTelegramAt`,
   * ADR-0067) — кабинет перестаёт предлагать связку везде разом, через
   * предикат `web/src/telegram/acceptsTelegramOffer.ts`. Отправку это не
   * глушит и глушить не должно: без личного чата с ботом
   * `PersonalChats.chatFor()` и так отдаёт `null`, слать уже некуда. Пара
   * «дата в базе → булево в DTO» — та же, что у `profileNamedAt` →
   * `needsProfile` выше. */
  noTelegram: boolean;
  /** Человек ещё не называл себя сам (`users.profileNamedAt` пуст, ADR-0044)
   * — кабинет спрашивает имя и фамилию один раз, экраном `/welcome`, и
   * пускает дальше. Не статус доступа: этот человек уже `active` и уже в
   * школе, просто зовётся пока тем, что дал Telegram, или заглушкой
   * `NEW_PERSON_NAME` после входа по почте. */
  needsProfile: boolean;
  /** Кабинет сейчас ведёт себя с этим человеком как с учеником (`users.studentModeAt`
   * есть, ADR-0163): `roles` выше уже пустые, экраны и уведомления ученические.
   * Режим включает и выключает только сам человек, `PUT /me/student-mode`. */
  studentMode: boolean;
  /** Режим ученика человеку доступен: у него настоящая роль штата (учитель,
   * помощник, админ). По `roles` это не вывести — в режиме они пустые, — поэтому
   * флаг приходит с сервера. «Профиль» показывает переключатель только при `true`;
   * включить режим по этому флагу нельзя, сервер проверяет роли заново. */
  canUseStudentMode: boolean;
}

/**
 * Тело `PUT /me/no-telegram` (ADR-0067). Одна ручка на оба направления:
 * `true` ставит отметку, `false` снимает. Отдельного «снять» нет нарочно —
 * человек, который завёл Telegram позже, обязан иметь дорогу назад, а два
 * маршрута на одно поле разъехались бы правами и валидацией.
 */
export interface SetNoTelegramInput {
  noTelegram: boolean;
}

/**
 * Тело `PUT /me/student-mode` (ADR-0163). Одна ручка на оба направления, как
 * `PUT /me/no-telegram`: `true` включает режим ученика (только у штата),
 * `false` выключает — это можно всегда, даже когда штатные экраны для человека
 * закрыты самим режимом.
 */
export interface SetStudentModeInput {
  enabled: boolean;
}

