// Правка списка на месте после точечной записи — расширение приёма
// ADR-0087 (`applyData`) со ставки на одну запись на списки: `PATCH`/`POST`/
// `DELETE` одного элемента уже возвращают этот элемент (или, для `DELETE`,
// не возвращают ничего, но однозначно называют id), второй `GET` того же
// списка не нужен — список правится локально из ответа самой записи.
//
// ПОЧЕМУ это годится: локальная правка верна ровно тогда, когда она даёт
// байт в байт то же самое, что вернул бы повторный `GET` этого списка прямо
// сейчас, — то есть запись не должна менять ничего, от чего зависит СОСТАВ
// или ПОРЯДОК уже показанной страницы (поле сортировки, поле фильтра).
//
// Проверено чтением сервиса для обоих мест, где это применяется сейчас
// (usePeople.ts, useGradingPresets.ts):
// - `GET /grading-presets` (GradingPresetsService.list) — без фильтра,
//   `.sort({ createdAt: 1 })` по возрастанию. У новой заготовки `createdAt`
//   «сейчас» — не меньше, чем у уже показанных, значит её место в конце,
//   туда же кладёт `appended`.
// - `GET /users` (UserRolesService.list, вызывается из UsersController.list)
//   — тоже без фильтра (`find({})`), но, вопреки виду «список без порядка»,
//   с сортировкой `.sort({ lastLoginAt: -1 })`: недавно вошедшие сверху.
//   `replacedById` в usePeople.ts всё равно даёт то же, что и свежий `GET`,
//   ПОТОМУ ЧТО ни `PATCH /users/:id` (роли), ни `PATCH /users/:id/status`
//   (статус) поле `lastLoginAt` не трогают — место элемента в уже
//   отсортированном списке не меняется, меняется только его содержимое.
//   Появится действие, которое одновременно двигает `lastLoginAt`, —
//   `replacedById` для него перестанет быть верным, понадобится `reload()`.
//
// ОГОВОРКА ПРО ЛИМИТ: список всегда читается с лимитом (CLAUDE.md «API»), и
// на самой его границе `withoutId` строго говоря расходится со свежим `GET`:
// удалив одну строку из полной страницы, сервер дослал бы следующую, а мы
// покажем на одну меньше. Для мест, где приём применяется, это не наступает —
// `usePeople.ts` просит `LIST_LIMIT_MAX` (200), а школа целиком меньше, — но
// список, который реально упирается в лимит и листается, так править нельзя.
//
// КОГДА НЕ ГОДИТСЯ: список с фильтром в запросе — например, будущий журнал
// рассылок по статусу. Отменённая рассылка обязана уйти из выборки
// «активные», а это решает `WHERE` на сервере, не клиент: `replacedById`
// показал бы отменённую строку там, где сервер её уже не отдал бы. Для
// такого списка — обычный `reload()`, не эти помощники.
//
// `null` на входе — `null` на выходе (список ещё не пришёл с первого `GET`,
// патчить нечего). Входной массив не мутируется — второй потребитель того же
// `data` не должен увидеть промежуточное состояние.

/** Заменить элемент с тем же `id`. Id не нашёлся — список возвращается без
 * изменений (не апсерт: для новой записи есть `appended`). */
export function replacedById<T extends { id: string }>(
  list: T[] | null,
  item: T,
): T[] | null {
  if (list === null) return null;
  return list.map((existing) => (existing.id === item.id ? item : existing));
}

/** Выкинуть элемент с этим `id`. Id не нашёлся — список возвращается без
 * изменений (но новым массивом, см. «не мутируй» выше). */
export function withoutId<T extends { id: string }>(
  list: T[] | null,
  id: string,
): T[] | null {
  if (list === null) return null;
  return list.filter((existing) => existing.id !== id);
}

/** Добавить в конец — верно только для списка, отсортированного так, что
 * новая запись там и оказалась бы (см. разбор `/grading-presets` выше). */
export function appended<T>(list: T[] | null, item: T): T[] | null {
  if (list === null) return null;
  return [...list, item];
}
