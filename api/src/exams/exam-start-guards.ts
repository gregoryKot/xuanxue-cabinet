// Два отказа на входе в новую попытку: форма не опубликована и срок сдачи
// прошёл (ADR-0125, решение владельца 2026-09-22 «1 вариант и дату сдачи
// тоже»). Отдельным файлом, а не строками в ExamAttemptsService.start(): тот
// уже выше потолка в 150 строк, а храповик такие файлы держит только на
// уменьшение (CLAUDE.md «Храповики»). Поднять его бейслайн было бы обходом
// гейта — вместо этого сюда уезжают и сами проверки, и объяснение, почему
// каждая стоит там, где стоит.
//
// Где именно она стоит и почему это важно: СТРОГО после ветки «уже идущая
// попытка возвращается» и никогда раньше. Идущую попытку срок не прерывает —
// она доживает свой лимит минут и сдаётся как обычно; иначе ученик, сдающий
// экзамен в момент наступления срока, терял бы доступ к собственной работе
// от простой перезагрузки страницы. На это есть отдельные тесты и в юните
// сервиса, и в e2e — именно потому, что ошибка тут не видна глазом.
//
// И до подсчёта `attemptsUsed`, не после: прошедший срок — то же самое «нет»
// при любом числе использованных попыток, но причина ученику называется
// точнее (срок, а не будто бы кончившиеся попытки), и лишнего запроса в базу
// не делается.
import type { DateTime } from 'luxon';
import {
  EXAM_DUE_PASSED_MESSAGE,
  EXAM_NOT_PUBLISHED_MESSAGE,
  isExamDuePassed,
  type ExamStatus,
} from '@xuanxue/shared';
import { InvalidInputError } from '../common/errors';

/** `dueAt` — как он лежит в DTO: ISO UTC с Z или его нет вовсе. Сравнение
 * само живёт в shared (`isExamDuePassed`), общее с кабинетом и ботом: две
 * реализации «срок прошёл» разошлись бы на первом же часовом поясе. */
export function assertExamNotPastDue(dueAt: string | undefined, now: DateTime): void {
  if (isExamDuePassed(dueAt, now.toMillis())) {
    throw new InvalidInputError(EXAM_DUE_PASSED_MESSAGE);
  }
}

/** ТЗ 4.4, п.1: на черновике и в архиве попытку не заводят. Стоит первой, до
 * поиска уже идущей попытки: у неопубликованной формы её просто не бывает. */
export function assertExamPublished(status: ExamStatus): void {
  if (status !== 'published') throw new InvalidInputError(EXAM_NOT_PUBLISHED_MESSAGE);
}
