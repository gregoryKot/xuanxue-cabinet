import { describe, expect, it } from 'vitest';
import { examItemEditorTitle } from './examItemEditorTitle';

describe('examItemEditorTitle', () => {
  it('вопроса ещё нет — «Новый вопрос»', () => {
    expect(examItemEditorTitle(null)).toBe('Новый вопрос');
  });

  it('пустая формулировка — тоже «Новый вопрос», а не пустой заголовок', () => {
    expect(examItemEditorTitle('   ')).toBe('Новый вопрос');
  });

  it('короткая формулировка — целиком, без многоточия', () => {
    expect(examItemEditorTitle('Зачем придумали тайцзи?')).toBe(
      'Зачем придумали тайцзи?',
    );
  });

  it('длинная формулировка — первые слова и многоточие', () => {
    expect(
      examItemEditorTitle(
        'Опишите ощущение в пояснице при сидении и объясните, зачем оно нужно',
      ),
    ).toBe('Опишите ощущение в пояснице при сидении…');
  });

  it('хвостовая запятая перед многоточием не остаётся', () => {
    expect(
      examItemEditorTitle('Первое, второе, третье, четвёртое, пятое, шестое, седьмое'),
    ).toBe('Первое, второе, третье, четвёртое, пятое, шестое…');
  });

  it('переводы строк и двойные пробелы считаются одним разделителем', () => {
    expect(examItemEditorTitle('Первое\n  второе')).toBe('Первое второе');
  });
});
