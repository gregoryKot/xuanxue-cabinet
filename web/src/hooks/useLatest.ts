// Значение последнего рендера для обработчика, который срабатывает позже
// рендера, где его создали: окончание загрузки файла приходит асинхронно, и
// замыкание видело бы данные на момент нажатия. Так второе видео варианта,
// загруженное параллельно, затирало первое (владелец, 2026-09-27).
import { useRef, type RefObject } from 'react';

export function useLatest<T>(value: T): RefObject<T> {
  const ref = useRef(value);
  ref.current = value;
  return ref;
}
