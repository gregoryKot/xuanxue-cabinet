// Название занятия для человека — «Тайцзицюань · средняя группа». У слота
// название и подпись группы — два поля (в посте канала группа идёт своей
// первой строкой), но по отдельности название ничего не различает: в неделе
// школы семь разных «Тайцзицюань». Экран «Занятия» печатал одно поле и
// показывал их подряд неотличимыми (снимок владельца 2026-10-02). Одна
// функция на кабинет и бота — чтобы второе место не забыло группу снова.

const GROUP_SEPARATOR = ' · ';

export function classDisplayName(cls: { title: string; groupLabel?: string }): string {
  const group = cls.groupLabel?.trim();
  return group ? `${cls.title}${GROUP_SEPARATOR}${group}` : cls.title;
}
